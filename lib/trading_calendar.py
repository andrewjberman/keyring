# The years the fallback covers, derived from the data. A date outside this range is NOT a
# trading-day answer under the fallback: it raises CalendarCoverageError (fail closed).
FALLBACK_FIRST_YEAR: int = min(int(_d[:4]) for _d in NYSE_HOLIDAYS_FALLBACK)
FALLBACK_LAST_YEAR: int = max(int(_d[:4]) for _d in NYSE_HOLIDAYS_FALLBACK)


class CalendarCoverageError(ValueError):
    """The active calendar source does not cover the requested year (fail closed, never a guess)."""


# Back-compat alias for the mdpf-local module's name (so its re-export is a clean rename).
_NYSE_HOLIDAYS_FALLBACK = NYSE_HOLIDAYS_FALLBACK


def _to_date(d: object) -> dt.date:
    if isinstance(d, dt.datetime):
        return d.date()
    if isinstance(d, dt.date):
        return d
    if isinstance(d, str):
        return dt.date.fromisoformat(d[:10])
    raise TypeError(f"unsupported date type: {type(d)!r}")


def _fallback_source() -> str:
    return "NYSE/hardcoded-fallback-%d-%d" % (FALLBACK_FIRST_YEAR, FALLBACK_LAST_YEAR)


_FALLBACK_ANNOUNCED = False


def _announce_fallback() -> None:
    """ONE stderr line per process the first time the fallback ANSWERS (IRPT_BCKEND-D2-W282-S3,
    2026-10-12): a consumer reading a trading-day answer from the hardcoded table could not tell
    it from the package's answer, and the table ends at FALLBACK_LAST_YEAR. ASCII, stderr, once;
    stdout untouched so a CLI's answer line is unchanged."""
    global _FALLBACK_ANNOUNCED
    if _FALLBACK_ANNOUNCED:
        return
    _FALLBACK_ANNOUNCED = True
    import sys
    sys.stderr.write(
        "WARN: trading_calendar: pandas_market_calendars absent; answering from the hardcoded NYSE "
        "fallback %s (covers %d-%d; regenerate with lib/tests/gen_nyse_closures.py --write before %d)\n"
        % (_fallback_source(), FALLBACK_FIRST_YEAR, FALLBACK_LAST_YEAR, FALLBACK_LAST_YEAR + 1))


def _require_covered(d: dt.date) -> None:
    """Fail closed: when the ACTIVE source is the fallback, a date whose year the fallback does
    not cover raises instead of answering. No-op when the package is the source. Under the
    fallback it also announces, once per process, that the fallback is the source (W282-S3)."""
    if _USE_PMC:
        return
    _announce_fallback()
    if not FALLBACK_FIRST_YEAR <= d.year <= FALLBACK_LAST_YEAR:
        raise CalendarCoverageError(
            "calendar source %s does not cover year %d (date %s); install pandas_market_calendars "
            "or extend the generated fallback" % (_fallback_source(), d.year, d.isoformat()))


def is_trading_day(date: object) -> bool:
    """True iff `date` is a NYSE trading day (weekday + not a NYSE holiday). Under the fallback,
    raises CalendarCoverageError for a year outside FALLBACK_FIRST_YEAR..FALLBACK_LAST_YEAR."""
    d = _to_date(date)
    _require_covered(d)
    if d.weekday() >= 5:
        return False
    if _USE_PMC:
        assert _NYSE is not None
        sched = _NYSE.valid_days(start_date=d.isoformat(), end_date=d.isoformat())
        return len(sched) == 1
    return d.isoformat() not in NYSE_HOLIDAYS_FALLBACK


def prev_trading_day(date: object) -> dt.date:
    """The NYSE trading day strictly before `date`."""
    c = _to_date(date) - dt.timedelta(days=1)
    _require_covered(c)
    while not is_trading_day(c):
        c -= dt.timedelta(days=1)
    return c


def first_trading_day_on_or_after(date: object, window: int = 14) -> dt.date | None:
    """The first NYSE trading day on or after `date` (round 132, FWD-5: the one business_date rule for every IRPT_DASHBD
    transaction producer). Looks at the `window` calendar days from `date` inclusive (window 14 is the producers' rule) and
    returns None when no trading day lies in that window. A Saturday or Sunday rolls forward to the Monday; a holiday to the
    next trading day. Uses is_trading_day, so the fail-closed coverage error of the fallback still propagates."""
    d = _to_date(date)
    for offset in range(window):
        candidate = d + dt.timedelta(days=offset)
        if is_trading_day(candidate):
            return candidate
    return None


def expected_last_trading_day(now: object) -> dt.date:
    """The expected last-SETTLED priced frontier as of `now`: today if today is a trading
    day, else the prior trading day. (Data priced T+1 should be at-or-after this date.)"""
    today = _to_date(now)
    return today if is_trading_day(today) else prev_trading_day(today)


def trading_days_behind(as_of: object, expected: object) -> int:
    """Trading days strictly after `as_of`, up to and including `expected` (0 if caught up).
    The frontier-aware staleness metric: 0 = at frontier, 1 = one trading day behind, etc."""
    a = _to_date(as_of)
    e = _to_date(expected)
    _require_covered(a)
    _require_covered(e)
    if a >= e:
        return 0
    n, c = 0, e
    while c > a:
        if is_trading_day(c):
            n += 1
        c -= dt.timedelta(days=1)
    return n


_WEEKDAY_NAMES = ("monday", "tuesday", "wednesday", "thursday", "friday", "saturday", "sunday")


def _to_weekday(weekday: object) -> int:
    """Weekday as 0=Monday..6=Sunday, from an int or a (case-insensitive) English name/3-letter abbreviation."""
    if isinstance(weekday, bool):
        raise TypeError("weekday must be an int 0-6 or a weekday name, not bool")
    if isinstance(weekday, int):
        if 0 <= weekday <= 6:
            return weekday
        raise ValueError(f"weekday int out of range 0-6: {weekday}")
    if isinstance(weekday, str):
        w = weekday.strip().lower()
        for i, n in enumerate(_WEEKDAY_NAMES):
            if w in (n, n[:3]):
                return i
    raise ValueError(f"unrecognised weekday: {weekday!r}")


def weekly_production_day(on_or_before: object, weekday: object) -> dt.date:
    """The most recent scheduled WEEKLY production day on or before `on_or_before`, for a producer
    that runs on `weekday` (int 0=Mon..6=Sun, or a name). The candidate is the latest calendar date
    <= `on_or_before` falling on that weekday. A candidate that is a Mon-Fri NYSE HOLIDAY rolls BACK
    to the prior trading day (the holiday-roll); a Saturday/Sunday candidate is never rolled -- a
    weekend producer's weekday is its own, not a trading-day question."""
    d = _to_date(on_or_before)
    wd = _to_weekday(weekday)
    c = d - dt.timedelta(days=(d.weekday() - wd) % 7)
    _require_covered(d)
    _require_covered(c)
    if c.weekday() < 5 and not is_trading_day(c):
        c = prev_trading_day(c)
    return c


def trading_days_between(start: object, end: object) -> list[dt.date]:
    """Inclusive list of NYSE trading days between `start` and `end`."""
    s = _to_date(start)
    e = _to_date(end)
    _require_covered(s)
    _require_covered(e)
    if s > e:
        return []
    if _USE_PMC:
        assert _NYSE is not None
        days = _NYSE.valid_days(start_date=s.isoformat(), end_date=e.isoformat())
        return [d.date() if hasattr(d, "date") else d for d in days]
    out: list[dt.date] = []
    cur = s
    one_day = dt.timedelta(days=1)
    while cur <= e:
        if is_trading_day(cur):
            out.append(cur)
        cur += one_day
    return out


def trading_days_mtd(date: object) -> list[dt.date]:
    """NYSE trading days from the 1st of `date.month` through `date` inclusive."""
    d = _to_date(date)
    return trading_days_between(dt.date(d.year, d.month, 1), d)


def trading_days_ytd(date: object) -> list[dt.date]:
    """NYSE trading days from Jan 1 of `date.year` through `date` inclusive."""
    d = _to_date(date)
    return trading_days_between(dt.date(d.year, 1, 1), d)


def total_trading_days_in_window(start: object, end: object) -> int:
    """Count of NYSE trading days in `[start, end]` inclusive."""
    return len(trading_days_between(start, end))


def calendar_source(date: object = None) -> str:
    """Provenance string for an artifact's `trading_day_calendar` field. The fallback's string
    carries its covered range (NYSE/hardcoded-fallback-2010-2027). With a `date`, raises
    CalendarCoverageError when the active source does not cover that date's year."""
    if date is not None:
        _require_covered(_to_date(date))
    return "NYSE/pandas_market_calendars" if _USE_PMC else _fallback_source()
