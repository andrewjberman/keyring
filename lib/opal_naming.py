def _norm_target(t):
    t = t.replace("\\", "/")
    return t[2:] if t.startswith("./") else t


def generate(out_dir, targets=None):
    """Write each generated file at its repo-relative path under out_dir. [(status, path, detail)]."""
    refusals, _warnings = validate()
    if refusals:
        raise RegistryError("the registry is refused (%d refusal(s)); run: python lib/opal_naming.py validate" % len(refusals))
    reg = load_registry()
    h16 = registry_hash()[:16]
    views = {v[0]: v for v in VIEWS}
    known = [v[0] for v in VIEWS] + [LOCALS_PATH, VECTORS_PATH]
    wanted = [_norm_target(t) for t in targets] if targets else known
    unknown = [t for t in wanted if t not in known]
    if unknown:
        raise RegistryError("not a generated file: %s (known: %s)" % (", ".join(unknown), ", ".join(known)))
    results = []
    for t in wanted:
        if t == VECTORS_PATH:
            try:
                text = json.dumps(dict({"_generated": MARK + h16}, vectors=build_vectors(reg)), indent=2) + "\n"
            except NotBuilt as exc:
                results.append(("SKIP", t, str(exc)))
                continue
        elif t == LOCALS_PATH:
            text = _gen_locals(reg, h16)
        else:
            text = _render_view(t, views[t][1], views[t][2], reg, h16)
        dst = os.path.join(out_dir, *t.split("/"))
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        with open(dst, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        results.append(("WROTE", t, "%d bytes" % len(text.encode("utf-8"))))
    return results


# --------------------------------------------------------------------------- CLI
def main(argv=None):
    ap = argparse.ArgumentParser(prog="opal_naming.py", description="the identity registry's validator and generator")
    sub = ap.add_subparsers(dest="cmd")
    v = sub.add_parser("validate", help="exit 0 if the registry is valid, 1 if refused")
    v.add_argument("--registry-dir")
    v.add_argument("--systems-file")
    g = sub.add_parser("generate", help="write the generated files under --out, at their repo-relative paths")
    g.add_argument("--out", required=True)
    g.add_argument("--target", action="append")
    sub.add_parser("vectors", help="print the name() vector JSON (cell EN-b-1)")
    c = sub.add_parser("census", help="grade names (DEC-7, cell EN-s-1)")
    c.add_argument("--names")
    c.add_argument("--live", action="store_true")
    c.add_argument("--repo", action="store_true")
    a = ap.parse_args(argv)

    if a.cmd == "validate":
        refusals, warnings = validate(a.registry_dir, a.systems_file)
        for w in warnings:
            print("WARN %s.%s: %s" % w)
        for r in refusals:
            print("REFUSED %s.%s: %s" % r)
        reg_dir = a.registry_dir or REGISTRY_DIR
        if refusals:
            print("VALIDATE: REFUSED %d refusal(s), %d warning(s)" % (len(refusals), len(warnings)))
            return 1
        reg = load_registry(reg_dir, a.systems_file)
        print("VALIDATE: OK %d system row(s), %d scope row(s), %d warning(s) at registry@%s" % (
            len(_systems(reg)), len(_scopes(reg)), len(warnings), registry_hash(reg_dir)[:16]))
        return 0
    if a.cmd == "generate":
        try:
            results = generate(a.out, a.target)
        except RegistryError as exc:
            print("ERROR: %s" % exc)
            return 1
        for status, t, detail in results:
            print("%s %s (%s)" % (status, t, detail))
        print("GENERATE: %d written, %d skipped, into %s at registry@%s" % (
            sum(1 for r in results if r[0] == "WROTE"), sum(1 for r in results if r[0] == "SKIP"),
            a.out, registry_hash()[:16]))
        return 0
    if a.cmd == "vectors":
        try:
            print(json.dumps(build_vectors(), indent=2))
            return 0
        except NotBuilt as exc:
            print("ERROR: %s" % exc)
            return 2
    if a.cmd == "census":
        print("ERROR: census is DEC-7's, cell EN-s-1, and is not in this module yet")
        return 2
    ap.print_help()
    return 2


if __name__ == "__main__":
    sys.exit(main())
