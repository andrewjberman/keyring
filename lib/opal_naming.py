def _separations(reg):
    """(pipeline dir, foreign buckets, foreign key prefixes) per firm pipeline tree: the other firms'
    provisioned legacy buckets, then their provisioned ruled buckets; and every spelling the tree's vendor
    uses for those firms in the monolith, then every spelling ANY OTHER vendor uses for them there.
    A foreign firm's slice under another vendor's prefix in the shared bucket (fidelity/alongside/, the
    multi-firm Wealthscape export, NFRA_FIDUPL) is still that firm's data to every other tree."""
    rows = []
    for s in _scopes(reg):
        for pt in s.get("pipeline_trees", []):
            foreign = [lookup(k, reg) for k in pt["separated_from"]]
            legacy = [a["spelling"] for g in foreign for a in g.get("aliases", [])
                      if "bucket" in a.get("planes", []) and a.get("provisioned")]
            ruled = [g["bucket"] for g in foreign if g.get("bucket_provisioned")]
            prefixes = ["%s/%s/" % (pt["vendor"], sp) for g in foreign
                        for sp in (g.get("monolith_scopes") or {}).get(pt["vendor"], [])]
            prefixes += ["%s/%s/" % (v, sp) for g in foreign
                         for v, sps in sorted((g.get("monolith_scopes") or {}).items()) if v != pt["vendor"]
                         for sp in sps]
            rows.append((pt["dir"], tuple(legacy + ruled), tuple(prefixes)))
    return rows


# --------------------------------------------------------------------------- rendering
def _py_lit(obj, indent=0):
    pad = " " * indent
    if isinstance(obj, dict):
        if not obj:
            return "{}"
        items = ["%s    %s: %s," % (pad, _py_lit(k), _py_lit(v, indent + 4)) for k, v in obj.items()]
        return "{\n%s\n%s}" % ("\n".join(items), pad)
    if isinstance(obj, tuple):
        return "(%s,)" % _py_lit(obj[0]) if len(obj) == 1 else "(%s)" % ", ".join(_py_lit(x) for x in obj)
    if isinstance(obj, list):
        return "[%s]" % ", ".join(_py_lit(x) for x in obj)
    if isinstance(obj, bool):
        return "True" if obj else "False"
    if obj is None:
        return "None"
    if isinstance(obj, str):
        return json.dumps(obj)
    return repr(obj)


def _js_str(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


def _begin(tag, h16, comment, path):
    return "%s %s [%s] -- do not edit by hand; regenerate with: python lib/opal_naming.py generate --out <dir> --target %s" % (
        comment, _view_mark(h16, path), tag, path)


def _end(tag, comment):
    return "%s END GENERATED [%s]" % (comment, tag)


def _block(tag, h16, comment, path, body):
    return [_begin(tag, h16, comment, path)] + body.split("\n") + [_end(tag, comment)]


def _adv_tenant(tid, s, own):
    """The tenant directories a firmId may read under platinum/advi/{tenant}/ (the advTenant remedy, LD-0442).
    One scope is ONE equivalence class: the scope's own tenant and each alias tenant of that scope, in that order.
    EVERY member lists EVERY member, because the PRD's tenant-assertion contract resolves the path's firm segment
    "aliases included, to one firm". The class is declared here and never inferred from a shared bucket."""
    own_tenant = s.get("tenant")
    if not own_tenant or own_tenant.get("pseudo"):
        raise RegistryError("tenant %r names scope %r, which carries no served tenant of its own" % (tid, s["key"]))
    return [s["key"]] + [a["spelling"] for a in s.get("aliases", []) if a.get("tenant")]


