def _find_marked(lines, tag, comment):
    begin = None
    for i, ln in enumerate(lines):
        s = ln.strip()
        if begin is None and s.startswith(comment) and MARK in s and ("[%s]" % tag) in s:
            begin = i
        elif begin is not None and s == _end(tag, comment):
            return begin, i + 1
    return None


def _py_span(text, tag):
    for node in ast.parse(text).body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name == tag:
            return min([node.lineno] + [d.lineno for d in node.decorator_list]) - 1, node.end_lineno
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == tag for t in node.targets):
            return node.lineno - 1, node.end_lineno
        if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name) and node.target.id == tag:
            return node.lineno - 1, node.end_lineno
    raise RegistryError("no top-level definition %r" % tag)


def _mjs_span(text, tag):
    lines = text.split("\n")
    start = next((i for i, ln in enumerate(lines) if ln.startswith("export const %s " % tag)), None)
    if start is None:
        raise RegistryError("no `export const %s`" % tag)
    end = next((j for j in range(start, len(lines)) if lines[j].strip() == "});"), None)
    if end is None:
        raise RegistryError("`export const %s` has no closing `});`" % tag)
    return start, end + 1


def _render_view(path, syntax, tags, reg, h16):
    base = _read_text(os.path.join(REPO, *path.split("/")))
    if syntax == "json":
        obj = json.loads(base)
        firms, pseudo = _firm_registry_rows(reg)
        out = {"_generated": "%s%s -- do not edit by hand; regenerate with: python lib/opal_naming.py generate"
                             " --out <dir> --target %s" % (MARK, h16, path)}
        for k, v in obj.items():
            if k != "_generated":
                out[k] = firms if k == "firms" else pseudo if k == "pseudo" else v
        out.setdefault("firms", firms)
        out.setdefault("pseudo", pseudo)
        return json.dumps(out, indent=2, ensure_ascii=False) + "\n"
    comment, span = ("//", _mjs_span) if syntax == "mjs" else ("#", _py_span)
    text = base
    for tag in tags:
        lines = text.split("\n")
        found = _find_marked(lines, tag, comment) or span(text, tag)
        text = "\n".join(lines[:found[0]] + BLOCKS[tag](reg, h16, path) + lines[found[1]:])
    if syntax == "py":
        ast.parse(text)
    return text


def _hcl(obj, indent=0):
    pad = " " * indent
    if isinstance(obj, dict):
        items = ["%s  %s = %s" % (pad, json.dumps(k), _hcl(v, indent + 2)) for k, v in obj.items()]
        return "{\n%s\n%s}" % ("\n".join(items), pad)
    if isinstance(obj, list):
        return "[%s]" % ", ".join(_hcl(x) for x in obj)
    return json.dumps(obj)


def _gen_locals(reg, h16):
    scopes = _scopes(reg)
    scope_long = {}
    for s in scopes:
        for sp in _spellings(s):
            scope_long[sp] = s["long"]
    parts = [
        "# %s%s -- do not edit by hand; regenerate with:" % (MARK, h16),
        "#   python lib/opal_naming.py generate --out <dir> --target %s" % LOCALS_PATH,
        "locals {",
        "  # every scope: long form -> short form (NAMING_SCHEMA.json resource.scope_form SHORT)",
        "  scope_short = " + _hcl({s["long"]: s["short"] for s in scopes}, 2),
        "  # every spelling lookup() resolves (long, short, alias) -> the long form",
        "  scope_long = " + _hcl(scope_long, 2),
        "  # every scope: long form -> its bucket (scopes.json)",
        "  scope_bucket = " + _hcl({s["long"]: s["bucket"] for s in scopes}, 2),
        "  # every firm: long form -> the fence's principal ARN globs (fence_patterns())",
        "  fence_patterns = " + _hcl({s["long"]: fence_patterns(s["long"], reg) for s in scopes if s["class"] == "FIRM"}, 2),
        "  # the account every fence pattern names (exemptions.json account_id)",
        "  account_id = " + json.dumps(reg["exemptions"]["account_id"]),
        "}",
    ]
    return "\n".join(parts) + "\n"


