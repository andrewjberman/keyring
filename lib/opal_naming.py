def _directives():
    """(the D-codes under `directives:`, {D-code: [project codes]}) from org/missions/DIRECTIVES.yaml.
    Read by line: bare python on this shell has no PyYAML (PRD DEC-1)."""
    codes, projects = set(), {}
    in_block, cur, buf = False, None, None
    for line in _read_text(DIRECTIVES_PATH).split("\n"):
        if re.match(r"^directives:\s*$", line):
            in_block = True
            continue
        if in_block and re.match(r"^\S", line):
            in_block = False
        m = re.match(r"^  (D[0-9]+):\s*$", line)
        if in_block and m:
            cur = m.group(1)
            codes.add(cur)
            projects.setdefault(cur, [])
            continue
        pm = re.match(r"^\s+projects:\s*\[(.*)$", line)
        if pm and cur:
            buf = pm.group(1)
        elif buf is not None:
            buf += " " + line.strip()
        if buf is not None and "]" in buf:
            projects[cur].extend(x.strip().strip("'\"") for x in buf.split("]")[0].split(",") if x.strip())
            buf = None
    return codes, projects


# --------------------------------------------------------------------------- lookups
def _spellings(row):
    """Every spelling lookup() resolves to this row: key, long, short, and each alias not marked lookup false."""
    out = [row.get("key"), row.get("long"), row.get("short")]
    out += [a.get("spelling") for a in row.get("aliases", []) if a.get("lookup", True)]
    return [s for s in dict.fromkeys(out) if s]


def lookup(scope, registry=None):
    """The scopes.json row for a long form, a short form or an alias, as a copy; else KeyError."""
    reg = registry or _registry()
    for row in _scopes(reg):
        if scope in _spellings(row):
            return json.loads(json.dumps(row))
    raise KeyError(scope)


def fence_patterns(firm_long, registry=None):
    """The IAM ARN globs matching principals that carry that firm's scope token (DEC-4 i).

    A resource name writes the scope in its SHORT form in the slot after the system
    (NAMING_SCHEMA.json resource.grammar), so the glob is role/*-{short}-*. An IAM glob cannot say
    "the second slot": a principal carrying the token in a later slot also matches, and that is the
    glob's stated limit."""
    reg = registry or _registry()
    row = lookup(firm_long, reg)
    if row.get("class") != "FIRM":
        raise KeyError("%s is a %s scope, not a firm" % (firm_long, row.get("class")))
    return ["arn:aws:iam::%s:role/*-%s-*" % (reg["exemptions"]["account_id"], row["short"])]


def _home_bucket(reg, scope_row, tier, source=None):
    """The bucket the tier home rule gives a tier for a scope's tenancy (tiers.json)."""
    home = reg["tiers"]["homes"][scope_row["tenancy"]][tier]
    if home["home"] == "shared":
        return home["bucket"]
    if home["home"] == "scope":
        return scope_row["bucket"]
    if home["home"] == "source":
        if not source:
            raise RegistryError("tier %s of a %s scope is homed by its source, and none was given"
                                % (tier, scope_row["tenancy"]))
        return lookup(source, reg)["bucket"]
    raise RegistryError("unknown home kind %r" % home["home"])


def _routed_bucket(scope_row):
    """The bucket the deployed router serves a scope's tenants from: its routed bucket alias, else its bucket."""
    for a in scope_row.get("aliases", []):
        if "bucket" in a.get("planes", []) and a.get("routed"):
            return a["spelling"]
    return scope_row["bucket"]


def _irpt_bucket(reg, scope_row):
    """The bucket the IRPT readers and writers address: the transitional live row (scopes.json product_live, keyed by
    the PRODUCT scope lookup() resolves for the IRPT product) while IRPT_BCKEND's move is pending, else the routed
    bucket. A scope with no such row keeps its routed bucket."""
    product = lookup("irpt", reg)["key"]
    live = ((scope_row.get("product_live") or {}).get(product) or {}).get("bucket")
    return live if live else _routed_bucket(scope_row)


def _tier_live_bucket(scope_row, tier):
    """The bucket a scope's data of one tier LIVES in today (scopes.json tier_live), or None.

    A transitional record of where a tier sits now; it never moves the served (routed) bucket."""
    return ((scope_row.get("tier_live") or {}).get(tier) or {}).get("bucket")


def _buckets_of_firms(reg):
    """Every provisioned bucket of a FIRM scope: its bucket and its bucket aliases."""
    out = []
    for s in _scopes(reg):
        if s.get("class") != "FIRM":
            continue
        if s.get("bucket_provisioned"):
            out.append(s["bucket"])
        out += [a["spelling"] for a in s.get("aliases", []) if "bucket" in a.get("planes", []) and a.get("provisioned")]
    return out


# --------------------------------------------------------------------------- validate
def validate(reg_dir=None, systems_file=None):
    """(refusals, warnings), each a list of (where, field, reason). No refusal means a valid registry."""
    refusals, warnings = [], []

    def refuse(where, field, reason):
        refusals.append((where, field, reason))

    try:
        reg = load_registry(reg_dir, systems_file)
    except (OSError, ValueError) as exc:
        return [("registry", "file", "unreadable: %s: %s" % (type(exc).__name__, exc))], []
    schema = load_schema()
    dcodes, dprojects = _directives()
    all_projects = {p for ps in dprojects.values() for p in ps}
    tiers = schema["key"]["tier"]
    refused_tokens = set(schema["refused_tokens"])
    reserved = set(schema["system"]["reserved"])
    standing_shared = set(schema["bucket"]["standing_shared"])
    homes = reg["tiers"].get("homes", {})
    scopes = _scopes(reg)
    systems = _systems(reg)
    system_rows = {s.get("key"): s for s in systems}
    tenant_kinds = reg["scopes"].get("tenant_kinds", [])

    try:
        _validate_reporting_policies(reg)
    except (ValueError, KeyError, TypeError) as exc:
        refuse("reporting_policies.json", "policies", str(exc))

    # tiers.json
    for tenancy, rule in homes.items():
        for tier in tiers:
            home = rule.get(tier)
            where = "tiers.json homes.%s" % tenancy
            if not isinstance(home, dict):
                refuse(where, tier, "no home for tier %s (NAMING_SCHEMA.json key.tier)" % tier)
            elif home.get("home") not in ("shared", "scope", "source"):
                refuse(where, tier, "home must be shared, scope or source")
            elif home["home"] == "shared" and home.get("bucket") not in standing_shared:
                refuse(where, tier, "a shared home names a bucket of NAMING_SCHEMA.json bucket.standing_shared")

    # scopes.json
    by_spelling = {}
    seen_scope_keys = set()
    firm_rows = {s.get("key"): s for s in scopes if s.get("class") == "FIRM"}
    for i, row in enumerate(scopes):
        where = "scopes.json[%d]" % i
        for f in ("key", "class", "long", "short", "tenancy", "bucket"):
            if not isinstance(row.get(f), str) or not row.get(f):
                refuse(where, f, "missing or empty")
        key, cls = row.get("key"), row.get("class")
        # The spelling check below compares a spelling to its OWNER key, so a key repeated across two rows
        # collides with nothing and passed silently -- and lookup() takes the FIRST match, so the second row
        # is dead while its tenancy/bucket disagree (SITEZ's two 'harvest' rows, 2026-09-21).
        if key in seen_scope_keys:
            refuse(where, "key", "%r is a repeated scope key; lookup() would use only the first row" % key)
        seen_scope_keys.add(key)
        if cls not in schema["key"]["scope_classes"]:
            refuse(where, "class", "%r is not one of NAMING_SCHEMA.json key.scope_classes" % cls)
        if row.get("tenancy") not in homes:
            refuse(where, "tenancy", "%r has no tier home rule in tiers.json" % row.get("tenancy"))
        if key != row.get("long"):
            refuse(where, "key", "a scope's key is its LONG form (NAMING_SCHEMA.json key.scope_form)")
        for f in ("key", "long", "short"):
            if row.get(f) in refused_tokens:
                refuse(where, f, "%r is a refused token (NAMING_SCHEMA.json refused_tokens): an alias only" % row.get(f))
        # A firm's forms are this row's long and short, their one home (RULING ONE): nothing else is compared.
        if "note" in row and (not isinstance(row["note"], str) or not row["note"]):
            refuse(where, "note", "a note is a non-empty string: the row's record of the ruling that shapes it")
        if cls in ("FIRM", "PRODUCT") and row.get("bucket") != "opal-data-%s" % row.get("long"):
            refuse(where, "bucket", "%r: a data bucket is opal-data-{scope}, LONG form (NAMING_SCHEMA.json bucket)" % row.get("bucket"))
        if cls == "GLOBAL":
            gs = schema["global_scope"]
            if (key, row.get("short")) != (gs["key"], gs["short"]):
                refuse(where, "key", "the global scope is %r / %r (NAMING_SCHEMA.json global_scope)" % (gs["key"], gs["short"]))
            if row.get("bucket") not in standing_shared:
                refuse(where, "bucket", "a GLOBAL scope names a standing shared bucket")
        if cls == "MASTER":
            firm = firm_rows.get(row.get("firm"))
            if not firm:
                refuse(where, "firm", "%r is not a FIRM scope row" % row.get("firm"))
            elif row.get("bucket") != firm.get("bucket"):
                refuse(where, "bucket", "a master's bucket is its firm's (%s)" % firm.get("bucket"))
            if (system_rows.get(row.get("vendor")) or {}).get("class") != "VENDOR":
                refuse(where, "vendor", "%r is not a VENDOR system row" % row.get("vendor"))
        if not isinstance(row.get("bucket_provisioned"), bool):
            refuse(where, "bucket_provisioned", "missing: true or false")
        if "tier_live" in row:
            tl = row["tier_live"]
            if not isinstance(tl, dict):
                refuse(where, "tier_live", "a dict of tier -> live record")
            else:
                for tier, live in tl.items():
                    lw = "%s.tier_live.%s" % (where, tier)
                    if tier not in tiers:
                        refuse(lw, "tier", "%r is not a tier of tiers.json (NAMING_SCHEMA.json key.tier)" % tier)
                    if not isinstance(live, dict):
                        refuse(lw, "record", "a dict of bucket, transitional, owner and expiry")
                        continue
                    if not isinstance(live.get("bucket"), str) or not live.get("bucket"):
                        refuse(lw, "bucket", "missing or empty")
                    if not isinstance(live.get("transitional"), bool):
                        refuse(lw, "transitional", "missing: true or false")
                    for f in ("owner", "expiry"):
                        if not isinstance(live.get(f), str) or not live.get(f).strip():
                            refuse(lw, f, "missing or empty")
        if "product_live" in row:
            pl = row["product_live"]
            if not isinstance(pl, dict):
                refuse(where, "product_live", "a dict of PRODUCT scope key -> transitional live record")
            else:
                for pkey, live in pl.items():
                    lw = "%s.product_live.%s" % (where, pkey)
                    try:
                        prow = lookup(pkey, reg)
                    except KeyError:
                        prow = {}
                    if prow.get("key") != pkey or prow.get("class") != "PRODUCT":
                        refuse(lw, "product", "%r is not a scope key of class PRODUCT in scopes.json" % pkey)
                    if not isinstance(live, dict):
                        refuse(lw, "record", "a dict of bucket, transitional, owner and expiry")
                        continue
                    if not isinstance(live.get("bucket"), str) or not live.get("bucket"):
                        refuse(lw, "bucket", "missing or empty")
                    if not isinstance(live.get("transitional"), bool):
                        refuse(lw, "transitional", "missing: true or false")
                    for f in ("owner", "expiry"):
                        if not isinstance(live.get(f), str) or not live.get(f).strip():
                            refuse(lw, f, "missing or empty")
        for sp in _spellings(row):
            if by_spelling.get(sp, key) != key:
                refuse(where, "aliases", "%r already resolves to scope %r" % (sp, by_spelling[sp]))
            by_spelling.setdefault(sp, key)
        for j, a in enumerate(row.get("aliases", [])):
            aw = "%s.aliases[%d]" % (where, j)
            if not isinstance(a.get("spelling"), str) or not a.get("spelling"):
                refuse(aw, "spelling", "missing or empty")
            if not isinstance(a.get("planes"), list) or not a.get("planes"):
                refuse(aw, "planes", "missing or empty")
            if "bucket" in (a.get("planes") or []) and not isinstance(a.get("provisioned"), bool):
                refuse(aw, "provisioned", "a bucket alias says whether the bucket exists")
            if a.get("tenant"):
                _check_tenant(a["tenant"], aw + ".tenant", tenant_kinds, refuse)
        if row.get("tenant"):
            _check_tenant(row["tenant"], where + ".tenant", tenant_kinds, refuse)
        for m in row.get("masters", []):
            mrow = next((s for s in scopes if s.get("key") == m), None)
            if not mrow or mrow.get("class") != "MASTER" or mrow.get("firm") != key:
                refuse(where, "masters", "%r is not a MASTER row of this firm" % m)
        for j, pt in enumerate(row.get("pipeline_trees", [])):
            for g in pt.get("separated_from", []):
                if g not in firm_rows:
                    refuse("%s.pipeline_trees[%d]" % (where, j), "separated_from", "%r is not a FIRM scope row" % g)
            if (system_rows.get(pt.get("vendor")) or {}).get("class") != "VENDOR":
                refuse("%s.pipeline_trees[%d]" % (where, j), "vendor", "%r is not a VENDOR system row" % pt.get("vendor"))
        for tname, tree in (row.get("trees") or {}).items():
            mrow = next((s for s in scopes if s.get("key") == tree.get("silver_master")), None)
            if not mrow or mrow.get("firm") != key:
                refuse("%s.trees.%s" % (where, tname), "silver_master", "%r is not a MASTER of this firm" % tree.get("silver_master"))

    # systems.json
    label = os.path.basename(systems_file) if systems_file else "systems.json"
    scope_spelling = {}
    for row in scopes:
        if row.get("class") in ("FIRM", "MASTER", "GLOBAL"):
            for sp in _spellings(row):
                scope_spelling.setdefault(sp, (row.get("class"), row.get("key")))
    refused_keys = {}
    for kind, members in reg["systems"].get("refused_keys", {}).items():
        if isinstance(members, list):
            for m in members:
                refused_keys[m] = kind
    unresolved = {u.get("token") for u in reg["systems"].get("unresolved", [])}
    seen = set()
    for i, row in enumerate(systems):
        where = "%s[%d]" % (label, i)
        key = row.get("key")
        if not isinstance(key, str) or not _KEY_RE.match(key or ""):
            refuse(where, "key", "%r: a system key is lowercase kebab-case ASCII" % key)
        if row.get("class") not in schema["system"]["classes"]:
            refuse(where, "class", "%r is not one of NAMING_SCHEMA.json system.classes" % row.get("class"))
        if not isinstance(row.get("long"), str) or not row.get("long"):
            refuse(where, "long", "missing or empty")
        if "short" in row and (not isinstance(row["short"], str) or not row["short"] or row["short"] in refused_tokens):
            refuse(where, "short", "present only where a short form is sanctioned, and never a refused token")
        # display_name: VENDOR rows carry the words a served face prints (VENDOR_DISPLAY_NAMES view); no other class does.
        # A MISSING word is a WARN, never a refusal: validate() refusing blocks the naming gate, and with enforcement on
        # that blocks every graded commit in the fabric (measured 2026-09-30, two VENDOR rows drained without words).
        # The view skips a row without words, so the served face reads its fallback for that vendor.
        if row.get("class") == "VENDOR":
            if "display_name" not in row:
                warnings.append((where, "display_name", "VENDOR row %r has no display_name: the vendor view omits it"
                                 " and the served face reads its fallback" % key))
            elif not isinstance(row["display_name"], str) or not row["display_name"].strip():
                refuse(where, "display_name", "present but not a non-empty string")
        elif "display_name" in row:
            refuse(where, "display_name", "only a VENDOR row carries display_name")
        od = row.get("owner_directive")
        if not od:
            refuse(where, "owner_directive", "missing -- every system row names the D-code of the directive that owns it,"
                   " resolving in org/missions/DIRECTIVES.yaml (LGIC_ENFORCE DEC-1)")
        elif not _DCODE_RE.match(str(od)) or od not in dcodes:
            refuse(where, "owner_directive", "%r does not resolve in org/missions/DIRECTIVES.yaml" % od)
        if row.get("owner_claim") not in (None, "measured", "inferred"):
            refuse(where, "owner_claim", "measured or inferred")
        elif row.get("owner_claim") == "inferred":
            warnings.append((where, "owner_directive", "%s for %r is inferred, owed a confirmation: %s"
                             % (od, key, row.get("owner_basis", ""))))
        if key in scope_spelling:
            cls, skey = scope_spelling[key]
            refuse(where, "key", "%r is a %s scope (scopes.json row %r); a firm is never a system"
                   " (NAMING_SCHEMA.json system.never_a_system)" % (key, cls, skey))
        if key in refused_tokens:
            refuse(where, "key", "%r is a refused token (NAMING_SCHEMA.json refused_tokens)" % key)
        if key in reserved:
            refuse(where, "key", "%r is reserved and never a row (NAMING_SCHEMA.json system.reserved)" % key)
        if key in schema["cadence"]["values"]:
            refuse(where, "key", "%r is a cadence, never a system (NAMING_SCHEMA.json system.never_a_system)" % key)
        if isinstance(key, str) and key.upper().replace("-", "_") in all_projects:
            refuse(where, "key", "%r is a project code in org/missions/DIRECTIVES.yaml, never a system" % key)
        if key in refused_keys:
            refuse(where, "key", "%r is a %s, never a system (systems.json refused_keys)" % (key, refused_keys[key]))
        if key in unresolved:
            refuse(where, "key", "%r is both a row and unresolved" % key)
        if key in seen:
            refuse(where, "key", "%r is a duplicate row" % key)
        seen.add(key)

    # exemptions.json
    ex = reg["exemptions"]
    if not re.match(r"^[0-9]{12}$", str(ex.get("account_id", ""))):
        refuse("exemptions.json", "account_id", "a twelve-digit account id")
    firm_buckets = set(_buckets_of_firms(reg))
    # A row's key set is CLOSED (NFRA_CTLPLN CT-d-2 AMENDMENT 4; CTO msg 106230): a reader meeting a key it does not know
    # REFUSES, never ignores, because the fence renders an ignored key as a FULL admission. `actions` and `prefix` are
    # the optional pair that scopes an exemption to those S3 actions under that key prefix (no GetObjectVersion, no
    # ListBucketVersions, and no write action but s3:PutObject, FB-g-23: it renders on the Deny side only, never an Allow).
    # The firm token a prefix must carry is read from scopes.json.
    row_keys = ("principal", "arn", "reason", "signoff_ref", "actions", "prefix")
    scoped_actions = ("s3:GetObject", "s3:ListBucket", "s3:GetBucketLocation", "s3:PutObject")
    bucket_firm = {}
    for s in scopes:
        if s.get("class") == "FIRM":
            bucket_firm[s.get("bucket")] = s.get("long")
            for a in s.get("aliases", []):
                if "bucket" in a.get("planes", []):
                    bucket_firm[a["spelling"]] = s.get("long")
    for bucket, rows in (ex.get("exemptions") or {}).items():
        if bucket not in firm_buckets:
            refuse("exemptions.json exemptions", bucket, "not a provisioned bucket of a FIRM scope in scopes.json")
        seen_principals = set()
        for j, r in enumerate(rows if isinstance(rows, list) else [None]):
            rwhere = "exemptions.json exemptions.%s[%d]" % (bucket, j)
            for f in ("principal", "reason", "signoff_ref"):
                if not isinstance(r, dict) or not isinstance(r.get(f), str) or not r.get(f):
                    refuse(rwhere, f, "missing or empty")
            if not isinstance(r, dict):
                continue
            for k in sorted(r):
                if k not in row_keys:
                    refuse(rwhere, k, "not a key an exemptions row carries (closed set: %s); an unknown key is refused, never"
                           " ignored, since a reader that ignored it would render the row as a FULL admission" % ", ".join(row_keys))
            raw_who = r.get("arn") if isinstance(r.get("arn"), str) and r.get("arn") else r.get("principal")
            who = raw_who
            if isinstance(who, str) and who:
                if not who.startswith("arn:"):
                    who = "arn:aws:iam::%s:role/%s" % (ex.get("account_id"), who)
                if who in seen_principals:
                    refuse(rwhere, "principal", "%r already has a row under this bucket: at most one row per principal per bucket" % who)
                seen_principals.add(who)
            if "actions" not in r and "prefix" not in r:
                continue
            if ("actions" in r) != ("prefix" in r):
                refuse(rwhere, "actions" if "actions" in r else "prefix", "actions and prefix come together or not at all")
                continue
            acts, pre = r["actions"], r["prefix"]
            if not (isinstance(acts, list) and acts and all(isinstance(a, str) and a in scoped_actions for a in acts)):
                refuse(rwhere, "actions", "a non-empty list drawn from the closed scoped set %s" % ", ".join(scoped_actions))
            # FB-g-19 (CTO round-3 ADDENDUM 9): prefix is one string or a non-empty list of strings; every member is held to
            # the rules of the string form, and the firm token is checked on every member
            # FB-g-21 (CTO round-3 ADDENDUM 10): a member NOT ending in / is an exact OBJECT KEY, held to the same rules (non-empty,
            # no leading /, no * or ?) and to the same firm-token check below
            pres = pre if isinstance(pre, list) else [pre]
            if not (isinstance(pre, (str, list)) and pres and all(
                    isinstance(p, str) and len(p) > 0 and not p.startswith("/") and not re.search(r"[*?]", p) for p in pres)):
                refuse(rwhere, "prefix", "a literal key prefix ending in / or an exact object key, non-empty, no leading / and no * or ?, or a non-empty list of them")
            elif any(len(p.split("/")) < 3 or p.split("/")[1] != bucket_firm.get(bucket) for p in pres):
                refuse(rwhere, "prefix", "its second path segment must be the firm token of this bucket (%r)" % bucket_firm.get(bucket))
            if not (isinstance(raw_who, str) and raw_who.startswith("arn:") and not re.search(r"[*?]", raw_who)):
                refuse(rwhere, "arn", "a scoped row names exactly one principal by its exact ARN (no * or ?)")

    # grants (ADVI_FIRMBKTS FB-g-21; CTO round-3 ADDENDUM 10): an Allow-only row admitting one principal to GetObject on exact object
    # keys. A CLOSED key set, refused never ignored (the module renders the same closed set); no prefix, no Deny, no exemption.
    grant_keys = ("principal", "arn", "reason", "signoff_ref", "actions", "keys")
    grant_required = ("principal", "reason", "signoff_ref", "actions", "keys")
    grant_actions = ("s3:GetObject",)
    for bucket, rows in (reg["exemptions"].get("grants") or {}).items():
        if bucket not in firm_buckets:
            refuse("exemptions.json grants", bucket, "not a provisioned bucket of a FIRM scope in scopes.json")
        for j, g in enumerate(rows if isinstance(rows, list) else [None]):
            gwhere = "exemptions.json grants.%s[%d]" % (bucket, j)
            if not isinstance(g, dict):
                refuse(gwhere, "row", "an object")
                continue
            for k in sorted(g):
                if k not in grant_keys:
                    refuse(gwhere, k, "not a key a grants row carries (closed set: %s); an unknown key is refused, never ignored"
                           % ", ".join(grant_keys))
            for k in grant_required:
                if k not in g:
                    refuse(gwhere, k, "missing")
            for f in ("principal", "reason", "signoff_ref"):
                if f in g and not (isinstance(g[f], str) and g[f]):
                    refuse(gwhere, f, "a non-empty string")
            if isinstance(g.get("principal"), str) and (g["principal"] == "*" or re.search(r"[*?]", g["principal"])):
                refuse(gwhere, "principal", "a principal ARN or role name, never * and no ? or *")
            if "arn" in g and not (isinstance(g["arn"], str) and g["arn"].startswith("arn:") and not re.search(r"[*?]", g["arn"])):
                refuse(gwhere, "arn", "an exact ARN starting arn: (no * or ?)")
            acts = g.get("actions")
            if not (isinstance(acts, list) and acts and all(isinstance(a, str) and a in grant_actions for a in acts)):
                refuse(gwhere, "actions", "a non-empty list drawn from %s" % ", ".join(grant_actions))
            keys_ = g.get("keys")
            if not (isinstance(keys_, list) and keys_ and all(
                    isinstance(k, str) and len(k) > 0 and not k.startswith("/") and not k.endswith("/") and not re.search(r"[*?]", k)
                    for k in keys_)):
                refuse(gwhere, "keys", "a non-empty list of exact object keys: non-empty, no leading /, no trailing /, no * or ?")

    # remediations.json
    known_buckets = firm_buckets | standing_shared | {s.get("bucket") for s in scopes}
    for i, r in enumerate(reg["remediations"].get("remediations", [])):
        where = "remediations.json[%d]" % i
        p, od = r.get("project"), r.get("owner_directive")
        if p not in all_projects:
            refuse(where, "project", "%r is not a project in org/missions/DIRECTIVES.yaml" % p)
        if od not in dcodes or p not in dprojects.get(od, []):
            refuse(where, "owner_directive", "%r: the directive whose projects list names %r" % (od, p))
        if not r.get("ranking_row"):
            refuse(where, "ranking_row", "missing or empty")
        if not r.get("surfaces"):
            refuse(where, "surfaces", "missing or empty")
        for j, sf in enumerate(r.get("surfaces") or []):
            sw = "%s.surfaces[%d]" % (where, j)
            if sf.get("kind") == "bucket-alias":
                try:
                    srow = lookup(sf.get("scope"), reg)
                except KeyError:
                    srow = {}
                if sf.get("alias") not in [a["spelling"] for a in srow.get("aliases", []) if "bucket" in a.get("planes", [])]:
                    refuse(sw, "alias", "%r is not a bucket alias of scope %r" % (sf.get("alias"), sf.get("scope")))
            elif sf.get("kind") == "s3-prefix":
                if sf.get("bucket") not in known_buckets or not str(sf.get("prefix", "")).endswith("/"):
                    refuse(sw, "prefix", "a known bucket and a prefix ending in /")
            else:
                refuse(sw, "kind", "bucket-alias or s3-prefix")

    # legacy_addresses.json: a READ address for a store that predates the canon. A row is refused for a
    # missing, extra or empty field, a repeated key, an unknown bucket, a shape/template mismatch, a template
    # whose placeholders are not exactly its params, or a reader that is not a project.
    leg_obj = reg.get("legacy_addresses")
    alias_buckets = {a["spelling"] for s in scopes for a in s.get("aliases", []) if "bucket" in a.get("planes", [])}
    # A pre-canon PLATFORM bucket (bucket.legacy_platform) is a legal bucket for a legacy READ row and nowhere else.
    legacy_platform = set(schema["bucket"].get("legacy_platform", []))
    seen_leg = set()
    for i, r in enumerate((leg_obj or {}).get("legacy_addresses", []) if isinstance(leg_obj, dict) else []):
        where = "legacy_addresses.json[%d]" % i
        if not isinstance(r, dict):
            refuse(where, "row", "not an object")
            continue
        if set(r) != set(LEGACY_FIELDS):
            refuse(where, "row", "fields must be exactly %s" % ", ".join(LEGACY_FIELDS))
            continue
        for f in LEGACY_FIELDS:
            if f != "params" and (not isinstance(r[f], str) or not r[f].strip()):
                refuse(where, f, "missing or empty")
        lkey, tmpl, params = r["key"], r["template"], r["params"]
        if not isinstance(lkey, str) or not _KEY_RE.match(lkey):
            refuse(where, "key", "%r: a legacy address key is lowercase kebab-case ASCII" % (lkey,))
        if lkey in seen_leg:
            refuse(where, "key", "%r is a repeated key" % (lkey,))
        seen_leg.add(lkey)
        if r["bucket"] not in known_buckets | alias_buckets | legacy_platform:
            refuse(where, "bucket", "%r is not a bucket scopes.json, bucket.standing_shared or bucket.legacy_platform knows" % (r["bucket"],))
        if r["shape"] not in ("object", "prefix"):
            refuse(where, "shape", "object or prefix")
        if isinstance(tmpl, str) and tmpl:
            if not tmpl.isascii() or tmpl.startswith("/") or (r["shape"] == "prefix") != tmpl.endswith("/"):
                refuse(where, "template", "ASCII, no leading /, and ending in / exactly when the shape is prefix")
            if not isinstance(params, list) or re.findall(r"\{([^{}]*)\}", tmpl) != params or len(set(params)) != len(params):
                refuse(where, "params", "exactly the template's {placeholders}, in order, none repeated")
        if r["reader"] not in all_projects:
            refuse(where, "reader", "%r is not a project in org/missions/DIRECTIVES.yaml" % (r["reader"],))

    # feeds.json (MDPF_CANON CN-c-2; CTO ruling msg 3457): a bronze feed row names its feed, its source (a systems key),
    # its scope (a scopes key, not the source) and its vendor (a VENDOR system row). A row is refused for a missing or
    # extra field, a repeated feed, an unknown source, scope or vendor, or a scope whose tenancy has no bronze home.
    feeds_obj = reg.get("feeds")
    scope_keys = {s.get("key") for s in scopes}
    seen_feeds = set()
    for i, r in enumerate((feeds_obj or {}).get("feeds", []) if isinstance(feeds_obj, dict) else []):
        where = "feeds.json[%d]" % i
        if not isinstance(r, dict):
            refuse(where, "row", "not an object")
            continue
        if set(r) != set(FEED_FIELDS):
            refuse(where, "row", "fields must be exactly %s" % ", ".join(FEED_FIELDS))
            continue
        feed = r["feed"]
        if not isinstance(feed, str) or not _FEED_RE.match(feed):
            refuse(where, "feed", "%r: a feed is lowercase ASCII letters, digits and underscores" % (feed,))
        if feed in seen_feeds:
            refuse(where, "feed", "%r is a repeated feed" % (feed,))
        seen_feeds.add(feed)
        if r["source"] not in system_rows:
            refuse(where, "source", "%r is not a systems.json key" % (r["source"],))
        if r["scope"] not in scope_keys:
            refuse(where, "scope", "%r is not a scopes.json key" % (r["scope"],))
        elif r["scope"] == r["source"]:
            refuse(where, "scope", "a product is never a scope beneath itself (NAMING_SCHEMA.json key.scope_rule)")
        else:
            try:
                _home_bucket(reg, lookup(r["scope"], reg), "bronze", r["source"])
            except (KeyError, RegistryError, ValueError) as exc:
                refuse(where, "scope", "no bronze home for %r: %s" % (r["scope"], exc))
        if (system_rows.get(r["vendor"]) or {}).get("class") != "VENDOR":
            refuse(where, "vendor", "%r is not a VENDOR system row" % (r["vendor"],))

    # resources.json (EN-r-4, PRD v1.2 DEC-1 E13; ruling 97177): {name, type, system, evidence} rows that
    # fill a {system} placeholder ONLY where the name's own tokens resolve none (NAMING_SCHEMA.json
    # grade.placeholder). A row is refused for a missing/extra/empty field, a repeated (name, type), a
    # system outside systems.json (or opal), a type the grade does not take, or a name whose own tokens
    # already resolve the SAME system (a redundant second carrier). A row naming a DIFFERENT system is an
    # override and passes (ruling 97177 amended 2026-09-21; _slots).
    graded_types = set(schema["kind"]["by_type"]) | set(schema["types_not_graded_by_kind"])
    res_obj = reg.get("resources") or {}
    res_rows = res_obj.get("resources") if isinstance(res_obj, dict) else None
    if isinstance(res_rows, list):
        seen_res = set()
        v_res = _Vocab(reg, schema)
        for i, r in enumerate(res_rows):
            where = "resources.json[%d]" % i
            if not isinstance(r, dict):
                refuse(where, "row", "not an object")
                continue
            extra = set(r) - set(RES_FIELDS)
            if extra:
                refuse(where, "row", "carries field(s) outside name, type, system, evidence: %s" % sorted(extra))
            for f in RES_FIELDS:
                if not isinstance(r.get(f), str) or not r.get(f).strip():
                    refuse(where, f, "missing or empty")
            name, typ, system = r.get("name"), r.get("type"), r.get("system")
            if isinstance(name, str) and isinstance(typ, str):
                rkey = (name, typ)
                if rkey in seen_res:
                    refuse(where, "name", "%r (type %r) is a repeated (name, type) row" % (name, typ))
                seen_res.add(rkey)
            if isinstance(system, str) and system.strip():
                if system == "opal":
                    refuse(where, "system", "'opal' is never a resource's system row (R2 fills that slot from the name itself)")
                elif system not in system_rows:
                    refuse(where, "system", "%r is not a systems.json key" % system)
            if isinstance(typ, str) and typ.strip() and typ not in graded_types:
                refuse(where, "type", "%r is not a node type the grade takes (NAMING_SCHEMA.json kind.by_type"
                       " or types_not_graded_by_kind)" % typ)
            if isinstance(name, str) and name.strip() and isinstance(typ, str) and typ.strip():
                try:
                    if typ == "SECRET":
                        segtoks = [t for t in (_res_tokens(s, v_res, "a secret") for s in name.split("/") if s) if t]
                        rflat, rheads = [], set()
                        for st in segtoks:
                            rheads.add(len(rflat))
                            rflat.extend(st)
                        if not rflat:
                            raise RaiseDefect("S1: %r has no token" % name)
                        _rsysv, _rout, _rscope, rph = _slots(None, rflat, typ, v_res, first_of_segment=rheads)
                    else:
                        body = name
                        if typ == "SQS_QUEUE" and name.endswith(".fifo"):
                            body = name[:-5]
                        rtoks = _res_tokens(body, v_res, "a resource name")
                        _rsysv, _rout, _rscope, rph = _slots(None, rtoks, typ, v_res)
                except (RaiseDefect, IndexError):
                    pass  # the tokeniser cannot place it here either; not this check's job to say why
                else:
                    if not rph and _rsysv == system:
                        refuse(where, "name", "%r already resolves %r from its own tokens (type %r);"
                               " a row naming the same system is redundant" % (name, system, typ))

    # platinum_destinations.json (ADVI_FIRMBKTS FB-f-9, CTO ADDENDUM 3): one row per served platinum class. A row is
    # refused for a missing, extra or empty field, a bucket that is neither a scopes.json bucket nor a bucket alias,
    # a legacy prefix that is not ASCII ending in / (or is repeated), a scope, source or tier that is not its key, a
    # reader that is not a project, or a destination the builder refuses (_platinum_build).
    pl_obj = reg.get("platinum_destinations")
    pl_rows = pl_obj.get("platinum_destinations", []) if isinstance(pl_obj, dict) else []
    seen_pl = set()
    for i, r in enumerate(pl_rows if isinstance(pl_rows, list) else []):
        where = "platinum_destinations.json[%d]" % i
        if not isinstance(r, dict):
            refuse(where, "row", "not an object")
            continue
        if set(r) != set(PLATINUM_FIELDS):
            refuse(where, "row", "fields must be exactly %s" % ", ".join(PLATINUM_FIELDS))
            continue
        if any(not isinstance(r[f], str) or not r[f].strip() for f in PLATINUM_FIELDS):
            for f in PLATINUM_FIELDS:
                if not isinstance(r[f], str) or not r[f].strip():
                    refuse(where, f, "missing or empty")
            continue
        if r["legacy_bucket"] not in known_buckets | alias_buckets:
            refuse(where, "legacy_bucket", "%r is not a bucket scopes.json or its aliases know" % (r["legacy_bucket"],))
        lp = r["legacy_prefix"]
        if not lp.isascii() or lp.startswith("/") or not lp.endswith("/"):
            refuse(where, "legacy_prefix", "ASCII, no leading /, and ending in /")
        if lp in seen_pl:
            refuse(where, "legacy_prefix", "%r is a repeated prefix" % (lp,))
        seen_pl.add(lp)
        if r["scope"] not in scope_keys:
            refuse(where, "scope", "%r is not a scopes.json key (a bucket is never a scope here)" % (r["scope"],))
        if r["source"] not in system_rows:
            refuse(where, "source", "%r is not a systems.json key" % (r["source"],))
        if r["tier"] not in tiers:
            refuse(where, "tier", "%r is not one of NAMING_SCHEMA.json key.tier" % (r["tier"],))
        if r["reader"] not in all_projects:
            refuse(where, "reader", "%r is not a project in org/missions/DIRECTIVES.yaml" % (r["reader"],))
        if r["scope"] in scope_keys and r["source"] in system_rows and r["tier"] in tiers:
            try:
                _platinum_build(reg, r)
            except (KeyError, RegistryError, ValueError) as exc:
                refuse(where, "table", "the builder refuses this destination: %s" % (exc,))

    _validate_firm_pages(reg, refuse)
    return refusals, warnings


def _validate_firm_pages(reg, refuse):
    """firm_pages.json (FWD-28; CTO ruling CT-v-2). A firm is a served tenant key of scopes.json, never null and never the
    word 'null' (the claim a request carries when it has no firm). An open route is a route of the data proxy (proxy_routes,
    carried as data), class (i) only, and names its pages explicitly: a wildcard such as ALL is refused. A firm row's page is
    in the union the GET /aum/metrics row names, and that row names no page no firm row admits. An absent file is an older
    package, which validates as before."""
    doc = reg.get("firm_pages")
    if doc is None:
        return
    where = "firm_pages.json"
    if not isinstance(doc, dict):
        refuse(where, "document", "a JSON object")
        return
    if set(doc) != set(FIRM_PAGES_KEYS):
        refuse(where, "keys", "the closed key set is %s" % ", ".join(FIRM_PAGES_KEYS))
    served = {tid for tid, _s, _t, _own in _tenants(reg)}
    internal = doc.get("internal_firm")
    if not isinstance(internal, str) or not internal:
        refuse(where, "internal_firm", "a non-empty string: the firm admitted by tier, not by a row")
    proxy = doc.get("proxy_routes")
    if not (isinstance(proxy, list) and proxy and all(isinstance(r, str) and re.match(r"^(GET|POST|PUT|DELETE) /", r) for r in proxy)
            and len(set(proxy)) == len(proxy)):
        refuse(where, "proxy_routes", "a non-empty list of distinct 'METHOD /path' route keys of the data proxy")
        proxy = []
    exempt = doc.get("exempt_pages")
    if not (isinstance(exempt, list) and all(isinstance(p, str) and p.startswith("/") for p in exempt)):
        refuse(where, "exempt_pages", "a list of page paths starting /")
    firms = doc.get("firms")
    pages_of = {}
    if not isinstance(firms, list) or not firms:
        refuse(where, "firms", "a non-empty list of firm rows")
        firms = []
    for i, row in enumerate(firms):
        rw = "%s firms[%d]" % (where, i)
        if not isinstance(row, dict) or set(row) - {"note"} != {"firm", "pages", "evidence"}:
            refuse(rw, "row", "fields must be exactly firm, pages, evidence, with an optional note")
            continue
        if "note" in row and (not isinstance(row["note"], str) or not row["note"]):
            refuse(rw, "note", "an optional non-empty string: the record and the date of the ruling that shapes the row")
        f = row["firm"]
        if f is None or f == "null":
            refuse(rw, "firm", "%r is never a firm value: no registry row names the claim of no firm" % (f,))
            continue
        if not isinstance(f, str) or f not in served:
            refuse(rw, "firm", "%r is not a served tenant key of scopes.json" % (f,))
            continue
        if f == internal:
            refuse(rw, "firm", "the internal firm is admitted by tier, never by a row")
        if f in pages_of:
            refuse(rw, "firm", "%r is a repeated firm row" % f)
        pages = row["pages"]
        if not (isinstance(pages, list) and pages and all(isinstance(p, str) and p.startswith("/") for p in pages)):
            refuse(rw, "pages", "a non-empty explicit list of page paths; a wildcard such as ALL is not a page list")
            continue
        pages_of[f] = set(pages)
    union = set().union(*pages_of.values()) if pages_of else set()
    seen = set()
    union_pages = None
    routes = doc.get("open_routes")
    if not isinstance(routes, list):
        refuse(where, "open_routes", "a list of open route rows")
        routes = []
    for i, r in enumerate(routes):
        rw = "%s open_routes[%d]" % (where, i)
        if not isinstance(r, dict) or set(r) != {"route", "class", "pages", "evidence"}:
            refuse(rw, "row", "fields must be exactly route, class, pages, evidence")
            continue
        rt = r["route"]
        if not isinstance(rt, str) or rt not in proxy:
            refuse(rw, "route", "%r is not a route of the data proxy (proxy_routes)" % (rt,))
        elif rt in seen:
            refuse(rw, "route", "%r is a repeated open route" % (rt,))
        else:
            seen.add(rt)
        if r["class"] != "i":
            refuse(rw, "class", "only a class (i) route is open to a partner firm; a class (ii) route stays internal-only")
        pages = r["pages"]
        if not (isinstance(pages, list) and pages and all(isinstance(p, str) and p.startswith("/") for p in pages)):
            refuse(rw, "pages", "a non-empty explicit list of page paths; a wildcard such as ALL is not a page list")
            continue
        if rt == FIRM_UNION_ROUTE:
            union_pages = set(pages)
        for p in pages:
            if p not in union:
                refuse(rw, "pages", "%r is a page no firm row admits" % p)
    if union_pages is None:
        refuse(where, "open_routes", "the union route %r is absent: it names the explicit page union" % FIRM_UNION_ROUTE)
    else:
        for f, ps in sorted(pages_of.items()):
            for p in sorted(ps - union_pages):
                refuse("%s firms[%s]" % (where, f), "pages", "%r is not in the union %r names: a new page needs its own row there" % (p, FIRM_UNION_ROUTE))
        for p in sorted(union_pages - union):
            refuse(where, "open_routes", "%r is named by %r but no firm row admits it" % (p, FIRM_UNION_ROUTE))


def _check_tenant(t, where, tenant_kinds, refuse):
    if t.get("pseudo"):
        for f in ("kind", "display_name", "note"):
            if not t.get(f):
                refuse(where, f, "missing or empty")
        return
    if t.get("kind") not in tenant_kinds:
        refuse(where, "kind", "%r is not one of scopes.json tenant_kinds" % t.get("kind"))
    if not t.get("display_name"):
        refuse(where, "display_name", "missing or empty")
    if not isinstance(t.get("enabled"), bool):
        refuse(where, "enabled", "true or false")
    s = t.get("surfaces")
    if not isinstance(s, dict) or not all(isinstance(v, bool) for v in s.values()):
        refuse(where, "surfaces", "a map of booleans")


