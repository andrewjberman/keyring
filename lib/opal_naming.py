def _kebab(label, value):
    if not isinstance(value, str) or not _KEY_RE.match(value):
        raise ValueError("%s must be lowercase kebab-case ASCII: %r" % (label, value))
    return value.split("-")


def _is_cadence(kind, schema):
    cad = schema["cadence"]
    return (kind in cad["values"] or bool(re.match(cad["interval_form"]["token_regex"], kind))
            or (kind.startswith("on-") and bool(re.match(cad["event_token_regex"], kind[3:]))))


# The scope classes name() takes in its scope slot; generated_locals.tf carries them as name_scope_classes.
NAME_SCOPE_CLASSES = ("FIRM", "GLOBAL", "MASTER")


def name(system, scope, function, kind, qualifier=None, fifo=False):
    """{system}-{scope}-{function}[-{qualifier}]-{kind} (NAMING_SCHEMA.json resource.grammar). Takes the scope's
    LONG form and writes its SHORT form (S4); scope None is a shared resource and carries no scope (S5). The
    kind is a kind.values member, or a cadence for an EVENT_RULE or SCHEDULE. fifo=True appends the AWS-required
    .fifo suffix after the kind, for an SQS_QUEUE kind only (NAMING_SCHEMA.json resource.fifo)."""
    reg, schema, v = _registry(), _schema(), _vocab()
    if fifo and kind not in schema["kind"]["by_type"]["SQS_QUEUE"]:
        raise ValueError("fifo is an SQS_QUEUE suffix; kind %r is not an SQS_QUEUE kind" % (kind,))
    if system != "opal" and system not in v.v1:
        raise ValueError("system %r is not a systems.json key (nor the reserved opal)" % (system,))
    body = []
    if scope is not None:
        body.append(_long_scope(reg, scope, NAME_SCOPE_CLASSES)["short"])
    words = _kebab("function", function) + (_kebab("qualifier", qualifier) if qualifier is not None else [])
    for t in words:
        if t in v.scope or t == "bd" or t in schema["refused_tokens"]:
            raise ValueError("%r in the function or qualifier is a scope or refused token; pass the scope as scope" % t)
    if not (kind in schema["kind"]["values"] or _is_cadence(kind, schema)):
        raise ValueError("kind %r is neither a NAMING_SCHEMA.json kind nor a cadence" % (kind,))
    nxt = (body + words)[0] if body + words else None
    if system == "opal" and nxt is not None and (nxt in v.v1 or nxt in v.v2):
        raise ValueError("opal before %r reads as a null prefix or an unresolved token (GRADING_RULE.md R2)" % nxt)
    return "-".join([system] + body + words + [kind]) + (".fifo" if fifo else "")


def secret_name(system, scope, purpose):
    """{system}/{scope}/{purpose} (NAMING_SCHEMA.json secret.grammar): the builder for a SECRET, which takes the
    slash grammar of Section S, not name()'s dash grammar. Takes the scope's LONG form and writes its SHORT form;
    scope None is a shared secret and carries no scope slot (S3). purpose is one or more lowercase kebab segments
    joined by / (S4), its last word the credential's kind (credentials, token, key, password, certificate)."""
    reg, schema, v = _registry(), _schema(), _vocab()
    if system != "opal" and system not in v.v1:
        raise ValueError("system %r is not a systems.json key (nor the reserved opal)" % (system,))
    parts = [system]
    if scope is not None:
        parts.append(_long_scope(reg, scope, NAME_SCOPE_CLASSES)["short"])
    if not isinstance(purpose, str) or not purpose:
        raise ValueError("purpose must be a non-empty string: %r" % (purpose,))
    segs = purpose.split("/")
    for seg in segs:
        for t in _kebab("purpose", seg):
            if t in v.scope or t == "bd" or t in schema["refused_tokens"]:
                raise ValueError("%r in the purpose is a scope or refused token; pass the scope as scope" % t)
    return "/".join(parts + segs)


# The shapes the vectors are built over: (system, function, qualifier, kind), each crossed with every
# FIRM, GLOBAL and MASTER scope row and with no scope.
_VECTOR_SHAPES = (("mdpf", "publisher", None, "role"), ("blackdiamond", "session", "gold", "lambda"),
                  ("opal", "ingress", None, "lb"), ("etfs", "netassets", None, "daily"))


def _type_of_kind(kind, schema):
    for t, kinds in schema["kind"]["by_type"].items():
        if kind in kinds:
            return t
    return "SCHEDULE" if _is_cadence(kind, schema) else None


def build_vectors(registry=None):
    """The name() vectors the Terraform module is proved against (DEC-3): each input, the node type its kind
    names, and name()'s output."""
    reg = registry or _registry()
    schema = _schema()
    scopes = [None] + [s["long"] for s in _scopes(reg) if s.get("class") in NAME_SCOPE_CLASSES]
    out = []
    for system, function, qualifier, kind in _VECTOR_SHAPES:
        for scope in scopes:
            out.append({"system": system, "scope": scope, "function": function, "qualifier": qualifier,
                        "kind": kind, "type": _type_of_kind(kind, schema),
                        "name": name(system, scope, function, kind, qualifier)})
    return out


def _norm_target(t):
    t = t.replace("\\", "/")
    return t[2:] if t.startswith("./") else t


def generate(out_dir, targets=None):
    """Write each generated file at its repo-relative path under out_dir. [(status, path, detail)]."""
    refusals, _warnings = validate()
    if refusals:
        raise RegistryError("the registry is refused (%d refusal(s)); run: python lib/opal_naming.py validate" % len(refusals))
    reg = load_registry()
    views = {v[0]: v for v in VIEWS}
    known = [v[0] for v in VIEWS] + [LOCALS_PATH, VECTORS_PATH, TFTEST_PATH]
    wanted = [_norm_target(t) for t in targets] if targets else known
    unknown = [t for t in wanted if t not in known]
    if unknown:
        raise RegistryError("not a generated file: %s (known: %s)" % (", ".join(unknown), ", ".join(known)))
    results = []
    for t in wanted:
        # Per-target hash (EN-r-6, row W1-S14): restricted to exactly the files TARGET_REGISTRY_KEYS names
        # for t, so a registry file this target does not read cannot move its mark.
        h16 = registry_hash(only=_target_registry_files(t))[:16]
        if t in (VECTORS_PATH, TFTEST_PATH):
            try:
                vectors = build_vectors(reg)
            except NotBuilt as exc:
                results.append(("SKIP", t, str(exc)))
                continue
            if t == VECTORS_PATH:
                text = json.dumps(dict({"_generated": _view_mark(h16, VECTORS_PATH)}, vectors=vectors), indent=2) + "\n"
            else:
                text = _gen_tftest(reg, h16, vectors)
        elif t == LOCALS_PATH:
            text = _gen_locals(reg, h16)
        else:
            text = _render_view(t, views[t][1], views[t][2], reg, h16)
        dst = os.path.join(out_dir, *t.split("/"))
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        with open(dst, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        results.append(("WROTE", t, "%d bytes" % len(text.encode("utf-8"))))
    return results


