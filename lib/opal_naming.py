def _find_marked(lines, tag, comment):
    begin = None
    for i, ln in enumerate(lines):
        s = ln.strip()
        if begin is None and s.startswith(comment) and MARK in s and ("[%s]" % tag) in s:
            begin = i
        elif begin is not None and s == _end(tag, comment):
            return begin, i + 1
    return None


def _py_span(text, tag):
    for node in ast.parse(text).body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name == tag:
            return min([node.lineno] + [d.lineno for d in node.decorator_list]) - 1, node.end_lineno
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == tag for t in node.targets):
            return node.lineno - 1, node.end_lineno
        if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name) and node.target.id == tag:
            return node.lineno - 1, node.end_lineno
    raise RegistryError("no top-level definition %r" % tag)


def _mjs_span(text, tag):
    lines = text.split("\n")
    if tag in MJS_BRACE_CLOSE_TAGS:
        # An object literal typed by annotation (`export const TAG: T = {`) that closes on a line that is exactly `}`.
        start = next((i for i, ln in enumerate(lines) if re.match(r"export const %s[ :=]" % re.escape(tag), ln)), None)
        if start is None:
            raise RegistryError("no `export const %s`" % tag)
        end = next((j for j in range(start, len(lines)) if lines[j] == "}"), None)
        if end is None:
            raise RegistryError("`export const %s` has no closing `}`" % tag)
        return start, end + 1
    start = next((i for i, ln in enumerate(lines) if ln.startswith("export const %s " % tag)), None)
    if start is None:
        raise RegistryError("no `export const %s`" % tag)
    end = next((j for j in range(start, len(lines)) if lines[j].strip() == "});"), None)
    if end is None:
        raise RegistryError("`export const %s` has no closing `});`" % tag)
    return start, end + 1


def _render_view(path, syntax, tags, reg, h16):
    if path in WHOLE_FILE_TARGETS:
        return "\n".join(ln for tag in tags for ln in BLOCKS[tag](reg, h16, path)) + "\n"
    base = _read_text(os.path.join(REPO, *path.split("/")))
    if syntax == "json":
        obj = json.loads(base)
        firms, pseudo = _firm_registry_rows(reg)
        out = {"_generated": "%s -- do not edit by hand; regenerate with: python lib/opal_naming.py generate"
                             " --out <dir> --target %s" % (_view_mark(h16, path), path)}
        for k, v in obj.items():
            if k != "_generated":
                out[k] = firms if k == "firms" else pseudo if k == "pseudo" else v
        out.setdefault("firms", firms)
        out.setdefault("pseudo", pseudo)
        return json.dumps(out, indent=2, ensure_ascii=False) + "\n"
    comment, span = ("//", _mjs_span) if syntax == "mjs" else ("#", _py_span)
    text = base
    for tag in tags:
        lines = text.split("\n")
        found = _find_marked(lines, tag, comment)
        if found is None and tag in AFTER_BLOCK:
            # first generation of a block that follows its anchor block: it lands right after the anchor's END line.
            # The first candidate anchor this carrier holds wins (a carrier may hold only one of them).
            anchor = None
            for cand in AFTER_BLOCK[tag]:
                anchor = _find_marked(lines, cand, comment)
                if anchor is not None:
                    break
            if anchor is None:
                raise RegistryError("%s: no [%s] block to follow for [%s]" % (path, " or ".join(AFTER_BLOCK[tag]), tag))
            found = (anchor[1], anchor[1])
        found = found or span(text, tag)
        text = "\n".join(lines[:found[0]] + BLOCKS[tag](reg, h16, path) + lines[found[1]:])
    if syntax == "py":
        ast.parse(text)
    return text


def _hcl(obj, indent=0):
    """HCL literal, rendered fmt-canonical: `terraform fmt` aligns an attribute group's `=` on the
    widest key, so a renderer emitting exactly one space produces a file `fmt -check` refuses at
    EVERY registry state -- alignment only, plan byte-identical (IRPT_BCKEND-W3-S47, rc=3 measured
    against both the live file and the pre-regen blob 6199adb8ec). The oracle is `terraform fmt
    -check` run on the generated file; this padding rule is never the evidence for itself."""
    pad = " " * indent
    if isinstance(obj, dict):
        keys = {k: json.dumps(k) for k in obj}
        width = max((len(v) for v in keys.values()), default=0)
        items = ["%s  %s%s = %s" % (pad, keys[k], " " * (width - len(keys[k])), _hcl(v, indent + 2))
                 for k, v in obj.items()]
        return "{\n%s\n%s}" % ("\n".join(items), pad)
    if isinstance(obj, list):
        return "[%s]" % ", ".join(_hcl(x) for x in obj)
    return json.dumps(obj)


def _platinum_prefixes(reg):
    """scope long form -> the canonical served-platinum prefix of that scope's bucket (ADVI_FIRMBKTS FB-g-13): the
    common directory path of every class template _platinum_build() places in the bucket the scope's rows land in,
    which must end in /platinum/ (RegistryError when it does not). A scope with no platinum row has no entry."""
    by_bucket = {}
    for row in _platinum_rows(reg):
        bucket, tmpl = _platinum_build(reg, row)
        by_bucket.setdefault(bucket, []).append((lookup(row["scope"], reg)["long"], tmpl))
    out = {}
    for bucket in sorted(by_bucket):
        items = by_bucket[bucket]
        common = []
        for segs in zip(*[t.split("/")[:-1] for _s, t in items]):
            if len(set(segs)) != 1:
                break
            common.append(segs[0])
        prefix = "/".join(common) + "/"
        if not prefix.endswith("/platinum/"):
            raise RegistryError("the platinum templates of bucket %s share %r, which does not end in /platinum/"
                                % (bucket, prefix))
        for scope in {s for s, _t in items}:
            out[scope] = prefix
    return out


def _class_prefixes(reg):
    """scope long form -> {legacy class prefix: canonical class directory} for every REGISTERED destination class
    (ADVI_FIRMBKTS FB-g-24; CTO act-0 ADDENDUM 1). The directory is the root of _platinum_build()'s template, the part
    before its {tail}, so it is the directory the seam's canonical destination of a key under the legacy prefix sits in;
    it ends in /. Built from the same derivation as platinum_prefix and ownership_key, never typed."""
    out = {}
    for row in sorted(_platinum_rows(reg), key=lambda r: r["legacy_prefix"]):
        _bucket, tmpl = _platinum_build(reg, row)
        if not tmpl.endswith(PLATINUM_TAIL) or not tmpl[:-len(PLATINUM_TAIL)].endswith("/"):
            raise RegistryError("the destination of class %r is %r, which does not end in a directory and %s"
                                % (row["legacy_prefix"], tmpl, PLATINUM_TAIL))
        scope = lookup(row["scope"], reg)["long"]
        out.setdefault(scope, {})[row["legacy_prefix"]] = tmpl[:-len(PLATINUM_TAIL)]
    return {scope: out[scope] for scope in sorted(out)}


