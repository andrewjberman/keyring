def _res_tokens(s, v, what):
    """G3 over a resource-name body: N3 separators, N2 camel split, N1 lowercase, N4 generated suffix.

    Pieces then rejoin into ONE token where they spell a vocabulary word: consecutive tokens joined by '-'
    (seeking-alpha, GRADING_RULE.md V1), or the camel pieces of one word joined whole (CloudWatch ->
    cloudwatch, a V3 purpose word). Rule text does not state the second (LGIC_ENFORCE-W1 row 9)."""
    if not _RES_CHARS.match(s):
        raise RaiseDefect("G3: the tokeniser cannot place a character of %s %r" % (what, s))
    pieces = []
    for i, seg in enumerate(re.split(r"[-_.]", s)):
        for p in _CAMEL_RE.split(seg):
            if p:
                pieces.append((p.lower(), i))
    if pieces and len(pieces[-1][0]) >= 14 and pieces[-1][0].isdigit():
        pieces.pop()  # N4
    out, i = [], 0
    while i < len(pieces):
        took = 1
        for j in range(min(len(pieces), i + 4), i + 1, -1):
            span = pieces[i:j]
            dashed = "-".join(p for p, _ in span)
            whole = "".join(p for p, _ in span)
            if dashed in v.vocab:
                out.append(dashed)
                took = j - i
                break
            if len({seg for _, seg in span}) == 1 and whole in v.vocab:
                out.append(whole)
                took = j - i
                break
        else:
            out.append(pieces[i][0])
        i += took
    return out


def _bd_is_vendor(toks, i, v):
    """R3: bd is the vendor when a firm token is next to it, before or after; the firm otherwise."""
    return (i > 0 and toks[i - 1] in v.firm) or (i + 1 < len(toks) and toks[i + 1] in v.firm)


def _r3_spell(toks, i, v):
    """R3 in a slot _slots() did not take: bd is refused in every slot, so a bd left in the function (or a
    secret's purpose) is spelled as the canonical form spells it -- blackdiamond when a firm token is next
    to it, else the firm's short form (the form R4 gives it). Any other token is returned unchanged."""
    # LGIC_ENFORCE-S87: THE FIRM BRANCH BELOW (`v.short[v.bd_firm]`) HAS NO OBSERVABLE OUTPUT TODAY, AND IT
    # STAYS. It is not unreachable -- it is reached and then subtracted. R3 spells a leftover bd with no
    # adjacent firm token as the firm's own short form; that is the SAME reading R4 has already written into
    # the scope slot, so FN1b (a function token equal to a token already written in the system or scope slot
    # is dropped) removes it, and no canonical form this function feeds can ever print it. Every other path
    # to a lone bd is taken by _slots() as the scope, or raises at R4 as two scopes. R3 and FN1b compose
    # exactly as written, so this is NOT a defect and NOT a repair site: changing either rule to make the
    # branch visible would be the defect. Removing the branch would need a proof that the composition can
    # never change, which nobody has -- so the fact is carried here instead, where whoever opens the file
    # reads it. Record: LGIC_ENFORCE-S87 (surfaced by 3.0.0_SA_CVO at L9, round 10) and the round-10
    # analysis section 3. Do not re-derive it; do not delete the branch on the strength of a coverage report.
    if toks[i] != "bd":
        return toks[i]
    return v.bd_vendor if _bd_is_vendor(toks, i, v) else v.short[v.bd_firm]


def _system_of(toks, i, v):
    t = toks[i]
    if t in v.v1:
        return t
    if t == "bd" and _bd_is_vendor(toks, i, v):
        return v.bd_vendor
    return None


def _alias_spell(toks, v, form):
    """V-4: replace each alias token in place. bd -> blackdiamond or the firm's form; a firm's long form or
    mockadv -> the short form (form 'short') or a short form -> the long one (form 'long')."""
    out = []
    for i, t in enumerate(toks):
        if t == "bd":
            if _bd_is_vendor(toks, i, v):
                out.append(v.bd_vendor)
            else:
                out.append(v.short[v.bd_firm] if form == "short" else v.bd_firm)
        elif t in v.scope:
            out.append(v.short[v.scope[t]] if form == "short" else v.scope[t])
        else:
            out.append(t)
    return out


_NO_SYSTEM_ASKED = "NO-SYSTEM-ASKED"
_PASCAL_POLICY = re.compile(r"^[A-Z][A-Za-z0-9]*[a-z][A-Za-z0-9]*$")  # one PascalCase token, no hyphen


def _slots(nm, toks, typ, v, first_of_segment=None):
    """R1-R4 over a token list: (system, removed indices, scope long or None, placeholder).
    placeholder is False, True (a blank is owed) or "NO-SYSTEM-ASKED" (the system slot is empty by ruling,
    sysv is ""): grade() reads the third as the fourth verdict, never as a blank.
    first_of_segment: the indices R1.d may read (a secret's segment heads, S2); None reads every token.
    nm: the name grade() received, exactly as passed -- the resources.json lookup key (EN-r-4). A row fills
    the {system} placeholder, AND a row whose system DIFFERS from the one the tokens resolve OVERRIDES it
    (1.0.0_SA_CTO, amending ruling 97177, 2026-09-21: a registered attribution outranks token inference --
    Andrew's CALL 2 files the find-* bright-data/lusha secrets under prospecting). Either way the row keeps
    every token in the function slot, so a name grades the same whether or not its vendor is a system key.
    A raise is never rescued by a row."""
    t1 = toks[0]
    sysv = _system_of(toks, 0, v)
    removed = set()
    placeholder = False
    if sysv:
        removed = {0}
    elif t1 == "opal":  # R2
        s2 = _system_of(toks, 1, v) if len(toks) > 1 else None
        if s2:
            sysv, removed = s2, {0, 1}
        elif len(toks) > 1 and toks[1] in v.v2:
            raise RaiseDefect("R2: %r after opal is an unresolved token (V2)" % toks[1])
        else:
            sysv, removed = "opal", {0}
    elif t1 in v.v2:
        raise RaiseDefect("R1.c: %r is an unresolved token (V2)" % t1)
    elif t1 in v.v3 or typ == "LAMBDA_LAYER":  # R1.d, R1.e
        sysv, placeholder = "{system}", True
        for j in range(1, len(toks)):
            if first_of_segment is not None and j not in first_of_segment:
                continue
            if toks[j] in v.v2:
                raise RaiseDefect("R1.d: the unresolved token %r (V2) comes before any system (V1)" % toks[j])
            s = _system_of(toks, j, v)
            if s:
                sysv, removed, placeholder = s, {j}, False
                break
        if placeholder and nm is not None:
            row_system = v.resources.get((nm, typ))
            if row_system:
                sysv, placeholder = row_system, False
        if placeholder and (t1 in v.purpose or typ == "LAMBDA_LAYER"
                            or (typ == "IAM_POLICY" and nm is not None and _PASCAL_POLICY.match(nm))):
            # NO-SYSTEM-ASKED (C-VERDICT, BF-t-2): an AWS service name, an inline policy name or a library layer
            # is never a system, and no later token or row resolved one. The system slot is empty, not blank.
            sysv, placeholder = "", _NO_SYSTEM_ASKED
    elif typ == "IAM_POLICY" and nm is not None and _PASCAL_POLICY.match(nm):
        # NO-SYSTEM-ASKED reaches an inline policy name whose first word is in NO vocabulary too (1.0.0_SA_CTO
        # ruling on ADVI_COTBKF-D2-S98, 2026-10-11): `RestrictedPrefixGetPutList` used to RAISE R1.f on
        # 'restricted' before the branch above could read it, so no inline policy named outside V1/V3 could be
        # graded at all. One PascalCase token is never a system; the slot is empty, not blank, not a defect.
        sysv, placeholder = "", _NO_SYSTEM_ASKED
    else:
        raise RaiseDefect("R1.f: %r is in no vocabulary; no registry row resolves it" % t1)
    if nm is not None and not placeholder:
        row_system = v.resources.get((nm, typ))
        if row_system and row_system != sysv:
            sysv, removed = row_system, set()
    longs, scope_idx = [], set()
    for i, t in enumerate(toks):
        if i in removed:
            continue
        if t in v.scope:
            longs.append(v.scope[t])
            scope_idx.add(i)
        elif t == "bd" and not _bd_is_vendor(toks, i, v):
            longs.append(v.bd_firm)
            scope_idx.add(i)
    if len(set(longs)) > 1:
        raise RaiseDefect("R4: two different scopes %s; a resource has one" % sorted(set(longs)))
    return sysv, removed | scope_idx, (longs[0] if longs else None), placeholder


def _cadence_slot(func, v):
    """R7: the last slot of an EVENT_RULE or SCHEDULE is a cadence (V6)."""
    if "on" in func[:-1]:
        k = func.index("on")
        if k < len(func) - 1:
            return func[:k], "-".join(func[k:]), False
    if func and (func[-1] in v.cadences or v.cadence_token.match(func[-1])):
        return func[:-1], func[-1], False
    for k in range(len(func) - 1, -1, -1):
        if func[k] in v.cadences or v.cadence_token.match(func[k]):
            return func[:k] + func[k + 1:], func[k], False
    return func, "{cadence}", True


def _fn1d(func, sysv, scope_long, typ, v):
    """R5's one subtraction (FN1d, NAMING_SCHEMA.json resource.function, v1.8), over the function slot R1
    and R4 (and R6/R7's kept last-slot token) have already taken out: remove, in one pass, every token
    written in the system or scope slot -- as the canonical form spells it (sysv; the scope's SHORT form) --
    AND every token that is this type's own kind (any kind in DATA.kind.by_type for typ; a type with no
    kind.by_type row, EVENT_RULE or SCHEDULE, has no own kind, so only system and scope tokens are removed).
    A placeholder system ({system}) writes no token and removes nothing. A function empty BEFORE this
    subtraction loses nothing to it (opal-gateway gives gateway-lb); a subtraction that empties a non-empty
    function RAISES (grade.unplaceable), whichever rule removed the last token."""
    if not func:
        return func
    drop = set()
    if sysv and sysv != "{system}":
        drop.add(sysv)
    if scope_long:
        drop.add(v.short[scope_long])
    drop |= set(v.kinds_by_type.get(typ, ()))
    out = [t for t in func if t not in drop]
    if not out:
        raise RaiseDefect("R5: the function subtraction (FN1d) leaves %r with no function token" % func)
    return out


def _grade_resource(nm, typ, v):
    if typ == "IAM_POLICY" and "#" in nm:  # R8: X#policy
        x, _, tail = nm.partition("#")
        if tail != "policy" or not x:
            raise RaiseDefect("R8: %r is not a resource policy name X#policy" % nm)
        if x in v.standing or x.startswith("opal-data-") or x.startswith("opal-%s-" % v.account):
            canon, ph, aliased = _grade_bucket(x, v)
        else:
            xt = _res_tokens(x, v, "a resource policy")
            owners = [t for t, ks in v.kinds_by_type.items() if xt and xt[-1] in ks]
            if len(owners) != 1:
                raise RaiseDefect("R8: the resource %r#policy names cannot be placed from its name" % x)
            canon, ph, aliased = _grade_resource(x, owners[0], v)
        return canon + "#policy", ph, (aliased + "#policy" if aliased else None)
    body, affix = nm, ""
    if typ == "SQS_QUEUE" and nm.endswith(".fifo"):  # N5
        body, affix = nm[:-5], ".fifo"
    toks = _res_tokens(body, v, "a resource name")
    if not toks:
        raise RaiseDefect("G3: %r has no token" % nm)
    sysv, out, scope_long, placeholder = _slots(nm, toks, typ, v)  # R1-R4
    func = [_r3_spell(toks, i, v) for i in range(len(toks)) if i not in out]  # R3: bd spelled in every slot
    if typ in ("EVENT_RULE", "SCHEDULE"):
        func, last, ph2 = _cadence_slot(func, v)  # R7
        placeholder = ph2 or placeholder  # a {cadence} blank (True) outranks NO-SYSTEM-ASKED
    else:
        kinds = v.kinds_by_type[typ]
        last = func.pop() if func and func[-1] in kinds else kinds[0]  # R6
    func = _fn1d(func, sysv, scope_long, typ, v)  # R5: the one subtraction (FN1d)
    parts = ([sysv] if sysv else []) + ([v.short[scope_long]] if scope_long else []) + func + [last]
    aliased = "-".join(_alias_spell(body.split("-"), v, "short")) + affix
    return "-".join(parts) + affix, placeholder, aliased  # R9


def _grade_secret(nm, v):
    """Section S: {system}/{scope}/{purpose}."""
    segtoks = [_res_tokens(s, v, "a secret") for s in nm.split("/") if s]
    segtoks = [st for st in segtoks if st]
    if not segtoks:
        raise RaiseDefect("S1: %r has no token" % nm)
    flat, heads, where = [], set(), []
    for si, st in enumerate(segtoks):
        heads.add(len(flat))
        for ti, t in enumerate(st):
            where.append(si)
            flat.append(t)
    sysv, out, scope_long, placeholder = _slots(nm, flat, "SECRET", v, first_of_segment=heads)  # S2 (system,
    # segment 1's first token, R1-R3) and S3 (scope: segment 2 when it is a V4 token, SHORT form, else the
    # secret is shared and the slot is omitted; a V4 token found anywhere else moves here) both reuse _slots.
    purpose = {}
    for i, t in enumerate(flat):
        if i not in out:
            purpose.setdefault(where[i], []).append(_r3_spell(flat, i, v))  # R3: bd spelled in every slot
    # S4: the purpose is every remaining segment, each lowercase kebab, joined by /.
    parts = ([sysv] if sysv else []) + ([v.short[scope_long]] if scope_long else [])         + ["-".join(purpose[k]) for k in sorted(purpose)]
    raw = [seg.split("-") for seg in nm.split("/")]
    spelled = _alias_spell([t for seg in raw for t in seg], v, "short")
    rebuilt, k = [], 0
    for seg in raw:
        rebuilt.append("-".join(spelled[k:k + len(seg)]))
        k += len(seg)
    return "/".join(parts), placeholder, "/".join(rebuilt)  # S5: system/scope/purpose, scope dropped if none


def _grade_log_group(nm, v):
    """Section L: /aws/{service}/{resource-name}; G2 (aws_fixed by-name) has already run."""
    if not nm.startswith("/"):
        raise RaiseDefect("L1: %r has no leading / and takes none of the three log-group shapes" % nm)
    parts = nm.split("/")
    l3 = len(parts) > 2 and parts[1] == "aws"
    if l3:
        if parts[2] == "vendedlogs" and len(parts) > 3:
            service, rest = "vendedlogs/" + parts[3], parts[4:]
        else:
            service, rest = parts[2], parts[3:]
    else:  # L4: never CONFORMANT, so never an alias of its canonical form either
        service, rest = parts[1], parts[2:]
    typ = _LOG_SERVICE.get(service)
    if typ is None:
        raise RaiseDefect("L2: service %r gives no resource type" % service)
    rest_s = "-".join(r for r in rest if r)
    affix = ""
    if rest_s.startswith("us-east-1."):  # N5
        affix, rest_s = "us-east-1.", rest_s[len("us-east-1."):]
    if not rest_s:
        raise RaiseDefect("L3: %r names no resource" % nm)
    canon, placeholder, aliased = _grade_resource(rest_s, typ, v)
    head = "/aws/%s/%s" % (service, affix)
    single = l3 and len(rest) == 1  # extra / segments joined with - are a change no alias makes
    return head + canon, placeholder, (head + aliased if aliased and single else None)


def _grade_bucket(nm, v):
    """Section B: opal-data-{scope} and opal-{account-id}-{purpose}. An S3_BUCKET_POLICY takes this same
    grammar: it carries its bucket's name exactly and is graded as that bucket (B5)."""
    if nm in v.standing:
        return nm, False, None  # B1
    if nm.startswith("opal-data-"):  # B2
        toks = nm[len("opal-data-"):].split("-")
        first = toks[0]
        if first in v.long_scope or first in v.products:
            long_, alias = first, False
        elif first == "bd" and _bd_is_vendor(toks, 0, v):
            return "opal-data-{scope}", True, None
        elif first in v.scope or first == "bd":
            long_, alias = v.scope.get(first, v.bd_firm), True
        elif first in v.vendors:
            return "opal-data-{scope}", True, None
        else:
            raise RaiseDefect("B2: %r after opal-data- is no scope key%s" % (first, " (V2)" if first in v.v2 else ""))
        canon = "opal-data-" + long_
        if len(toks) > 1:
            return canon, False, None
        return canon, False, (canon if alias else None)
    if nm.startswith("opal-"):  # B3
        toks = nm[len("opal-"):].split("-")
        if toks[0] == v.account:
            return nm, False, None
        if v.account in toks:
            toks.remove(v.account)
        return "opal-%s-%s" % (v.account, "-".join(toks)), False, None
    return "opal-%s-%s" % (v.account, nm), False, None  # B4


def _legacy_list(v):
    path = os.path.join(REPO, *v.list_home.split("/"))
    if not os.path.isfile(path):
        raise RaiseDefect("K7: the LIST %s is absent and this key's verdict turns on membership" % v.list_home)
    return [p.split("/") for p in _read_json(path)["paths"]]


def _seg_re(seg):
    out, pos = "", 0
    for m in _VAR_RE.finditer(seg):
        out += re.escape(seg[pos:m.start()]) + "[^/]*"
        pos = m.end()
    return re.compile("^" + out + re.escape(seg[pos:]) + "$")


def _seg_match(tseg, kseg):
    return bool(_seg_re(tseg).match(kseg) or (_is_var(kseg) and _seg_re(kseg).match(tseg)))


def _on_list(entries, segs, prefix):
    """K7: segment by segment; a prefix matches an entry's leading segments."""
    for e in entries:
        if (len(e) == len(segs) or (prefix and len(e) > len(segs))) and all(_seg_match(a, b) for a, b in zip(e, segs)):
            return True
    return False


def _new_served(rest, prefix):
    """K4a's NEW served path forms, below the tier: segments. A partition segment that is not an entity
    partition {entity}={id} RAISES (grade.unplaceable) -- its entity is the key column's name, which the
    name does not carry and no source outside it fills, so {entity} is never a placeholder (grade.placeholder
    names the system, source, scope and cadence slots only): never a bare id, a literal or a variable."""
    out = []
    leaf = None if prefix or not rest else len(rest) - 1
    if leaf == 0 and "." not in rest[0]:
        leaf = None
    # A TRAILING {entity}={id} IS A PARTITION, NOT THE FILE LEAF (LGIC_CANON-W8-S1). address() writes
    # .../advisors/advisor_id=A123 and this function read that last segment as the leaf, so it kebab-lowered
    # the entity id's own bytes -- grading the builder's own output OUT-OF-PATTERN and contradicting
    # NAMING_SCHEMA key.partition's example. The dot test is :1413's, reused deliberately rather than
    # replaced: a segment carrying a dot stays a leaf, so a malformed file like `foo=bar.json` is graded
    # exactly as before and this does not widen what the grader accepts.
    if leaf is not None and "." not in rest[leaf] and _ENTITY.match(rest[leaf]):
        leaf = None
    for i, s in enumerate(rest):
        if i == leaf:
            probe = _VAR_RE.sub("x", s)
            out.append(s if _KEBAB_JSON.match(probe) else s.lower().replace("_", "-"))
        elif i == 0:
            out.append(_table(s))
        elif _ENTITY.match(s):
            out.append(s)
        else:
            raise RaiseDefect("K4a: %r is not an entity partition {entity}={id}" % s)
    return out


def _table(s):
    """K3: a table is snake_case; a kebab or capitalised table is rewritten lowercase with - as _."""
    if _is_var(s) or "." in s or _SNAKE.match(s):
        return s
    return s.lower().replace("-", "_")


def _k5a(after, v):
    """K5.a: a V1 key next, then a scope. (source, scope long, consumed)."""
    source = scope = None
    k = 0
    if after and after[0] in v.v1:
        source, k = after[0], 1
        if k < len(after):
            s = after[k]
            if s in v.long_scope or s in v.products:
                scope, k = s, k + 1
            elif s in v.scope or s == "bd":
                scope, k = v.scope.get(s, v.bd_firm), k + 1
    return source, scope, k


def _grade_key(nm, v):
    """Section K: {source}/{scope}/{tier}/{table}/{partition}[/{object}]."""
    sp = nm.find(" ")
    key_, annot = (nm[:sp], nm[sp:]) if sp >= 0 else (nm, "")  # N5
    prefix = key_.endswith("/")
    segs = key_.split("/")
    if prefix:
        segs = segs[:-1]
    if not segs or any(s == "" for s in segs):
        raise RaiseDefect("K0: %r has an empty segment" % nm)
    bucket_scope, had_bucket = None, False
    if segs[0] in v.buckets:
        # A bucket is the key's container, never a segment of it (NAMING_SCHEMA.json key.container). A bucket
        # the registry knows is taken out, and it fills the slots it decides (K5.c): a firm's bucket, the scope.
        # K1 as written RAISES here (LGIC_ENFORCE-W1 row 10).
        had_bucket, bucket_scope = True, v.bucket_firm.get(segs[0])
        segs = segs[1:]
        if not segs:
            raise RaiseDefect("K1: %r is a bucket with no key" % nm)
    s1 = segs[0]
    placeholder = False
    aliased = None
    if s1 == "code" or s1 in v.tiers:  # K6, K5
        tier_first = s1 != "code"
        after = segs[1:]
        source, scope, k = _k5a(after, v)
        tail = after[k:]
        if tier_first and s1 == "platinum":  # K5.b
            srcs = [e[0] for e in _legacy_list(v) if _on_list([e[3:]], tail, prefix)]
            if source is not None and source in srcs:
                srcs = [source]
            if srcs:
                if source is None and len(set(srcs)) == 1:
                    source = srcs[0]
            else:
                tail = _new_served(tail, prefix)  # K4a
        if source is None:
            source, placeholder = "{source}", True
        if scope is None:
            scope = bucket_scope or "{scope}"
            placeholder = placeholder or bucket_scope is None
        out = [source, scope, s1 if tier_first else "code"] + tail
    elif s1 in v.v1:  # K2-K4
        out, i = [s1], 1
        if i < len(segs):
            s = segs[i]
            if _is_var(s) or s in v.long_scope or s in v.products:
                out.append(s)
                i += 1
            elif s in v.scope or s == "bd":
                out.append(v.scope.get(s, v.bd_firm))
                i += 1
                if not had_bucket:
                    aliased = True
            elif bucket_scope:
                out.append(bucket_scope)
            else:
                out.append("{scope}")
                placeholder = True
        tier = None
        if i < len(segs):
            s = segs[i]
            if s in v.tiers or _is_var(s):
                tier = s
                out.append(s)
                i += 1
            else:
                # K3: the name does not carry its tier and no source outside it fills one, so this is not a
                # placeholder (grade.placeholder names the system, source, scope and cadence slots only).
                raise RaiseDefect("K3: %r is not a tier (V7)" % s)
        rest = segs[i:]
        if tier == "platinum":
            if _on_list(_legacy_list(v), out + rest, prefix):
                out += rest  # K4a: a legacy served path keeps its bytes
            else:
                out += _new_served(rest, prefix)  # K4a
        elif rest:
            out += ([rest[0]] if tier == "code" else [_table(rest[0])]) + rest[1:]  # K3, K4b
    else:
        raise RaiseDefect("K1: segment 1 %r is neither a source nor a tier" % s1)
    canon = "/".join(out) + ("/" if prefix else "") + annot
    if aliased:
        aliased = "/".join(segs[:1] + [canon.split("/")[1]] + segs[2:]) + ("/" if prefix else "") + annot
    return canon, placeholder, (aliased or None)


_GRAMMARS = {"R": _grade_resource, "S": lambda n, t, v: _grade_secret(n, v), "L": lambda n, t, v: _grade_log_group(n, v),
             "B": lambda n, t, v: _grade_bucket(n, v), "K": lambda n, t, v: _grade_key(n, v)}


def grade(name, type):
    """(verdict, canonical_form) for a name of a node type, by LGIC_NAMING's GRADING_RULE.md.

    The verdict is NO-SYSTEM-ASKED, CONFORMANT, ALIAS or OUT-OF-PATTERN, with the canonical form; NOT-GRADED (canonical None)
    for a type outside the grade's domain (G1.2) or a name NAMING_SCHEMA.json aws_fixed puts outside it
    (G2.1 by name, read from the schema at run time; G2.2 by ARN is the caller's job -- grade(name, type)
    never receives an ARN). A name the rule cannot place raises RaiseDefect, naming the step. The canonical
    form fills every slot it can and carries a placeholder ({system}, {source}, {scope} or {cadence}, exactly
    the set grade.placeholder allows) for each slot it cannot: it never guesses."""
    v = _vocab()
    if type not in v.types:
        raise RaiseDefect("G1.1: %r is not a node type of NAMING_SCHEMA.json" % (type,))
    if type in v.not_graded:
        return "NOT-GRADED", None  # G1.2
    if not isinstance(name, str) or not name or not name.isascii():
        raise RaiseDefect("G3: %r is not a non-empty ASCII name" % (name,))
    # G2.1: NAMING_SCHEMA.json aws_fixed.by_name, read at run time -- never hand-listed. G2.2 (by ARN) is
    # outside grade()'s reach: grade(name, type) never receives an ARN, so the caller that holds the node's
    # ARN applies that exclusion before it calls grade() and does not grade an AWS-managed IAM_POLICY here.
    if _aws_fixed(type, name, None, _schema()):
        return "NOT-GRADED", None
    grammar = "R" if type in v.kinds_by_type else _OTHER_GRAMMAR.get(type)
    if grammar is None:
        raise RaiseDefect("G1.3: %r takes no grammar in GRADING_RULE.md" % type)
    canon, placeholder, aliased = _GRAMMARS[grammar](name, type, v)  # V-1: the canonical form, by the
                                                                      # grammar of the type
    if placeholder == _NO_SYSTEM_ASKED:
        return _NO_SYSTEM_ASKED, canon  # no system is asked of this kind of name (C-VERDICT); no remedy owed
    if placeholder:
        return "OUT-OF-PATTERN", canon  # G6; V-2
    if canon == name:
        return "CONFORMANT", canon  # V-3
    if aliased is not None and aliased == canon:
        return "ALIAS", canon  # V-4
    return "OUT-OF-PATTERN", canon  # V-5


def _segment(label, value):
    if not isinstance(value, str) or not value or "/" in value or not value.isascii() or value != value.strip():
        raise ValueError("%s must be a non-empty ASCII string with no '/' and no outer space: %r" % (label, value))
    return value


def _long_scope(reg, scope, classes=None):
    try:
        row = lookup(scope, reg)
    except KeyError:
        raise ValueError("scope %r resolves to no scopes.json row" % (scope,)) from None
    if scope != row["long"]:
        raise ValueError("scope %r is not the LONG form: pass %r" % (scope, row["long"]))
    if classes and row.get("class") not in classes:
        raise ValueError("scope %r is a %s scope; this slot takes %s" % (scope, row.get("class"), "/".join(classes)))
    return row


def key(source, scope, tier, table, partition):
    """Exactly {source}/{scope}/{tier}/{table}/{partition} (NAMING_SCHEMA.json key.grammar). The source is a
    systems.json key, the scope a LONG form, the tier one of key.tier. A bucket is never an argument."""
    reg = _registry()
    for label, val in (("source", source), ("scope", scope), ("tier", tier), ("table", table), ("partition", partition)):
        _segment(label, val)
    if source not in {s["key"] for s in _systems(reg)}:
        raise ValueError("source %r is not a systems.json key" % source)
    _long_scope(reg, scope)
    if scope == source:
        raise ValueError("a product is never a scope beneath itself (NAMING_SCHEMA.json key.scope_rule)")
    if tier not in _schema()["key"]["tier"]:
        raise ValueError("tier %r is not one of NAMING_SCHEMA.json key.tier" % tier)
    return "%s/%s/%s/%s/%s" % (source, scope, tier, table, partition)


def address(source, scope, tier, table, partition, object=None):
    """s3://{bucket}/{key}[/{object}]: the bucket is the tier home rule's for the scope's tenancy (tiers.json)."""
    k = key(source, scope, tier, table, partition)
    reg = _registry()
    try:
        bucket = _home_bucket(reg, lookup(scope, reg), tier, source)
    except (KeyError, RegistryError) as exc:
        raise ValueError("no home bucket for tier %s of scope %s: %s" % (tier, scope, exc)) from None
    out = "s3://%s/%s" % (bucket, k)
    if object is not None:
        if not isinstance(object, str) or not object or object.startswith("/") or not object.isascii():
            raise ValueError("object must be a non-empty ASCII string not starting with '/': %r" % (object,))
        out += "/" + object
    return out


def legacy_address(key, **params):
    """s3://{bucket}/{key} for a store that predates the canon: the one row of
    infra/logic/registry/legacy_addresses.json whose key this is, its template filled from params. A READ
    address only. KeyError for a key no row carries; ValueError for params that are not exactly the row's."""
    doc = _registry().get("legacy_addresses")
    if not isinstance(doc, dict):
        raise RegistryError("infra/logic/registry/legacy_addresses.json is absent from this package")
    for row in doc.get("legacy_addresses", []):
        if row.get("key") == key:
            break
    else:
        raise KeyError("no legacy_addresses.json row carries key %r" % (key,))
    if set(params) != set(row["params"]):
        raise ValueError("legacy address %r takes exactly %s; got %s" % (key, row["params"], sorted(params)))
    for label, val in params.items():
        _segment(label, val)
    return "s3://%s/%s" % (row["bucket"], row["template"].format(**params))


def _validate_reporting_policies(reg):
    """Validate closed, registered placement records without changing tier homes."""
    doc = reg.get("reporting_policies")
    if not isinstance(doc, dict) or set(doc) != {"schema_version", "policies"}:
        raise ValueError("reporting policy document has an invalid field set")
    if doc["schema_version"] != "reporting-policies-v1" or not isinstance(doc["policies"], list):
        raise ValueError("unknown reporting policy schema")
    required = {"policy_id", "policy_revision", "register_id", "register_path", "register_commit",
                "ruling_commit", "retention_policy_id", "source", "product_scope", "firms", "state",
                "enforcement_ref", "physical_disposal", "families"}
    seen = set()
    for policy in doc["policies"]:
        if not isinstance(policy, dict) or set(policy) != required:
            raise ValueError("reporting policy has an invalid field set")
        revision = policy["policy_revision"]
        if not isinstance(revision, str) or not _KEY_RE.fullmatch(revision) or revision in seen:
            raise ValueError("reporting policy revision missing, malformed or duplicated")
        seen.add(revision)
        if policy["register_id"] != "X10" or policy["register_path"] != "infra/logic/06_CONFORMANCE_LEDGER.md":
            raise ValueError("reporting placement requires the canonical X10 carrier")
        if not isinstance(policy["register_commit"], str) or not re.fullmatch(r"[0-9a-f]{40}", policy["register_commit"]):
            raise ValueError("reporting register requires an immutable full commit")
        if policy["state"] not in {"PENDING_ENFORCEMENT", "ACTIVE", "DISABLED"}:
            raise ValueError("unknown reporting policy state")
        if policy["state"] == "ACTIVE" and not re.fullmatch(r"[0-9a-f]{40}", policy["enforcement_ref"] or ""):
            raise ValueError("active policy requires an accepted enforcement commit")
        if policy["physical_disposal"] != "OPEN":
            raise ValueError("X10 grants no physical disposal activation")
        if policy["source"] not in {s["key"] for s in _systems(reg)}:
            raise ValueError("reporting source is not registered")
        product = _long_scope(reg, policy["product_scope"], {"PRODUCT"})
        if not product.get("bucket"):
            raise ValueError("reporting product bucket is not registered")
        firms = policy["firms"]
        if not isinstance(firms, list) or not firms or len(set(firms)) != len(firms):
            raise ValueError("reporting firms must be a nonempty unique list")
        for firm in firms:
            row = _long_scope(reg, firm, {"FIRM"})
            if row.get("tenant", {}).get("enabled") is not True or row["tenant"].get("kind") != "client":
                raise ValueError("reporting firm must be an enabled private client")
        families = policy["families"]
        if not isinstance(families, dict) or not families:
            raise ValueError("reporting families are required")
        # A family owns its table whole (content-addressed keys from the destination builder), or
        # names one fixed served object (IRPT_DASHBD-S12: manifest.json, series.json.gz and summary.json
        # share the served table "reporting"); a table is either one whole family or objects only.
        whole, objects = set(), {}
        for family, spec in families.items():
            if not re.fullmatch(r"[A-Z]+(?:_[A-Z]+)*", family):
                raise ValueError("malformed reporting family")
            fields = {"tier", "table", "extension", "unreferenced_days", "accepted_ceiling_days"}
            if not isinstance(spec, dict) or set(spec) not in (fields, fields | {"object"}):
                raise ValueError("reporting family metadata has an invalid field set")
            if spec["tier"] not in {"state", "platinum"} or not re.fullmatch(r"[a-z]+(?:_[a-z]+)*", spec["table"]):
                raise ValueError("reporting tier/table is not admitted")
            if spec["extension"] not in {"csv", "json", "json.gz", "pdf"}:
                raise ValueError("reporting content format is not admitted")
            if spec["tier"] == "platinum" and spec["extension"] not in {"json", "json.gz"}:
                raise ValueError("reporting platinum must be bounded JSON")
            if "object" in spec:
                obj = spec["object"]
                if not isinstance(obj, str) or not re.fullmatch(r"[a-z]+(?:_[a-z]+)*\." + re.escape(spec["extension"]), obj):
                    raise ValueError("reporting fixed object must be a plain name with the family extension")
                if spec["table"] in whole or obj in objects.setdefault(spec["table"], set()):
                    raise ValueError("reporting families must have distinct tables or distinct objects")
                objects[spec["table"]].add(obj)
            else:
                if spec["extension"] == "json.gz":
                    raise ValueError("gzip JSON is admitted only for a fixed served object")
                if spec["table"] in whole or spec["table"] in objects:
                    raise ValueError("reporting families must have distinct tables")
                whole.add(spec["table"])
            ceiling, draft = spec["accepted_ceiling_days"], spec["unreferenced_days"]
            if type(ceiling) is not int or not 0 < ceiling <= 2555:
                raise ValueError("reporting accepted ceiling must be finite")
            if draft is None:
                if spec["tier"] != "platinum":
                    raise ValueError("only accepted-only platinum may omit an unreferenced lifetime")
            elif type(draft) is not int or not 0 < draft <= min(30, ceiling):
                raise ValueError("reporting unreferenced lifetime must be finite")


def reporting_policy(policy_revision):
    """Fresh canonical metadata; pending/disabled records grant no writable address.

    Consumers persist policy_sha256 with their records and require exact equality
    across producer/reader composition. Never infer activation from an environment
    flag or the register's documentary grant alone.
    """
    reg = load_registry()
    _validate_reporting_policies(reg)
    rows = [p for p in reg["reporting_policies"]["policies"] if p["policy_revision"] == policy_revision]
    if len(rows) != 1:
        raise ValueError("unknown reporting policy revision")
    row = rows[0]
    digest = hashlib.sha256(json.dumps(row, sort_keys=True, separators=(",", ":"),
                                      allow_nan=False).encode("utf-8")).hexdigest()
    return {**row, "policy_sha256": digest}


def _reporting_destination(policy, firm, family, artifact_id, sha256):
    reg = load_registry()
    _long_scope(reg, firm, {"FIRM"})
    if firm not in policy["firms"] or family not in policy["families"]:
        raise ValueError("firm or family outside reporting policy")
    if not isinstance(artifact_id, str) or not re.fullmatch(
            r"(?:RPT-[0-9a-f]{32}|ART-[0-9a-f]{64}|sel_[0-9a-f]{64})", artifact_id):
        raise ValueError("reporting artifact requires a server-issued opaque identity")
    if not isinstance(sha256, str) or not re.fullmatch(r"[0-9a-f]{64}", sha256):
        raise ValueError("reporting artifact requires an exact content digest")
    spec = policy["families"][family]
    if "object" in spec:
        raise ValueError("a fixed served object is addressed by address(), not the X10 destination builder")
    prefix = key(policy["source"], firm, spec["tier"], spec["table"], artifact_id)
