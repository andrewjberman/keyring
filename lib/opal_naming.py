"""lib/opal_naming.py -- the identity registry's reader, validator and generator (LGIC_ENFORCE).

Cell EN-r-1 (PRD candidate E2; DEC-1, DEC-5) builds this file's first half:

    validate        refuse a registry row the schema or the register does not admit
    generate        write each DEC-5 carrier as a GENERATED view of the registry, into a directory
    lookup()        the scopes.json row for a long form, a short form or an alias
    fence_patterns()  the IAM ARN globs matching principals that carry a firm's scope token
    registry_hash() sha256 over the registry files, the stamp every generated file carries

Cell EN-b-1 (PRD candidate E3; DEC-2) builds the second half:

    key()           {source}/{scope}/{tier}/{table}/{partition}, exactly
    address()       s3://{bucket}/{key}[/{object}], the bucket from the tier home rule, never an argument
    name()          {system}-{scope}-{function}[-{qualifier}]-{kind}, the scope's SHORT form from its LONG
    grade()         (verdict, canonical_form) by LGIC_NAMING's GRADING_RULE.md; RaiseDefect on a RAISE
    vectors         the name() vectors the Terraform module is proved against

Cell EN-s-1 (PRD candidate E9; DEC-7) adds census mode: `census` judges the repo and the live plane with grade(),
and the first RAISE stops the run with the string printed.

THE REGISTRY is infra/logic/registry/*.json (DEC-1). The closed enumerations (tiers, cadences, the scope
classes, the system classes, the firm forms, the refused tokens) are org/standards/NAMING_SCHEMA.json's:
this module reads that file at run time and copies none of it. Standard library only. Loaded by path:
lib/ has no __init__.py.

A GENERATED VIEW. A carrier keeps its own file, and its bytes outside the definitions this module owns
there. Each owned definition is rewritten between a BEGIN line carrying
`GENERATED by lib/opal_naming.py from infra/logic/registry@<16 hex>` and an END line. A JSON carrier's
registry-derived keys are rewritten whole, and a top-level "_generated" key carries the mark. The first
generation is byte-equivalent in what each carrier exports (DELTA=0).

ASCII only.
"""
