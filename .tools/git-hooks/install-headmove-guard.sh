#!/usr/bin/env bash
# install-headmove-guard.sh -- Idempotent bootstrap for the destructive-HEAD-move guard.
#
# Usage: bash .tools/git-hooks/install-headmove-guard.sh
#
# ADHC_OWNPTH.010 (CTO Option A, 2026-05-18). The guard is a `git()` shell-shadow
# function -- NOT a git hook. The reference-transaction hook mechanism was
# withdrawn after AE 0.5.0's Phase-4 fixtures proved it deterministically hangs
# `git rebase` on Windows Git Bash.
#
# This installer appends a sentinel-guarded block to `~/.bashrc` that sources
# `.tools/git-hooks/headmove-guard.sh`. Every bash shell that loads the profile
# (including Claude Code Bash-tool shells) then has the `git()` shadow active.
#
#   - `~/.bashrc` is user-local, not repo-tracked -- so each agent runs this
#     installer once at startup (org/XXX.md Step-1b), mirroring install-owned-paths.sh.
#   - Idempotent: a sentinel marker guards against a double-append.
#   - Sources the tracked file (not an inlined copy) so guard updates flow
#     without a re-install.
#
# Exit codes:
#   0 = guard wired or already present (idempotent no-op)
#   1 = headmove-guard.sh source not found (Phase 1 not shipped)
#
# Design mirrors .tools/git-hooks/install-owned-paths.sh (ADHC_OWNPTH.003).

set -euo pipefail

REPO_ROOT="$(git rev-parse --show-toplevel 2>/dev/null || pwd)"
GUARD_SRC="$REPO_ROOT/.tools/git-hooks/headmove-guard.sh"
BASHRC="${HEADMOVE_BASHRC:-$HOME/.bashrc}"   # HEADMOVE_BASHRC is a test seam
MARKER="ADHC_OWNPTH.010 headmove-guard"
BEGIN="# >>> ${MARKER} >>>"
END="# <<< ${MARKER} <<<"

# Gate: Phase 1 must be shipped
if [ ! -f "$GUARD_SRC" ]; then
    echo "ERROR: $GUARD_SRC not found -- ADHC_OWNPTH.010 Phase 1 (git() function) must ship first." >&2
    exit 1
fi

# Idempotency: sentinel already present -> no-op
if [ -f "$BASHRC" ] && grep -qF "$MARKER" "$BASHRC" 2>/dev/null; then
    echo "OK: headmove-guard already wired in $BASHRC (idempotent no-op)"
    exit 0
fi

# Append the guarded block. The `source` line is itself guarded with a
# file-existence test so a moved/missing workspace cannot break the shell.
{
    echo ""
    echo "$BEGIN"
    echo "# Sources the ADHC_OWNPTH.010 git() destructive-HEAD-move guard."
    echo "# Re-generated by .tools/git-hooks/install-headmove-guard.sh -- do not hand-edit."
    echo "[ -f \"$GUARD_SRC\" ] && . \"$GUARD_SRC\""
    echo "$END"
} >> "$BASHRC"

echo "OK: headmove-guard wired into $BASHRC"
echo "     sources: $GUARD_SRC"

# Verification: confirm the git() shadow is defined in a fresh login shell.
if command -v bash >/dev/null 2>&1; then
    VERIFY="$(bash -lic 'type -t git' 2>/dev/null | tr -d '\r' || true)"
    if [ "$VERIFY" = "function" ]; then
        echo "VERIFIED: 'git' resolves to a shell function in a fresh login shell"
    else
        echo "WARN: fresh-login-shell verification did not report 'git' as a function" >&2
        echo "      (type -t git = '${VERIFY:-<empty>}'); the block is appended -- a new shell will pick it up." >&2
    fi
fi
exit 0
