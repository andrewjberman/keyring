#!/usr/bin/env python3
"""NFRA_CTLPLN round 19, cell CT-ai-2 (FWD-23): the seat record, generated from the laptop seat list alone.

GENERATE (default, and whenever --verify-only is absent): one table row per seat of the list
(serial, kind, live, doing, project, drive, orders, commit age, summary), a DOING-NOTHING line naming each seat
whose DOING reads IDLE or whose commit age is over 120 minutes, and the finished-work lines of
`round-close-check.py --project NFRA_CTLPLN --round 18` (ROUND-CLOSE, REVIEWER-ON-BOX, ORDERS, PROOFS, GRADED)
copied verbatim. No seat log is opened.

VERIFY: re-reads the record against the list and prints, as its last line,
    SEAT-RECORD seats=<n> named=<k> idle_flagged=<m> round_close_reviewer=<present|absent> ok=<True|False>
ok = every seat of the list is named in the record, the DOING-NOTHING line equals the list's set, and the
ROUND-CLOSE reviewer reads present. Exit 0 when ok, else 1.

MUTANT: generate from a copy of the list with one seat removed, then verify against the real list:
    python .tools/tests/test_round19_seat_record.py --gen-list <copy-minus-one-seat.json> --record <scratch.md>
The verifier must print ok=False (named < seats).
"""
import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PROJECT = "NFRA_CTLPLN"
ROUND = "18"
STALE_MINUTES = 120
DEFAULT_LIST = ROOT / "org" / "devices" / "state" / "laptop" / "seats.json"
DEFAULT_RECORD = (ROOT / "org" / "missions" / "D0" / "NFRA" / "NFRA_CTLPLN" / "deliverables"
                  / "0.9.0_WK_NFRA_CTLPLN~107" / "SEAT_LIST_READ.md")
ROUND_CLOSE = ROOT / ".tools" / "round-close-check.py"


def ascii_safe(value):
    return str(value).encode("ascii", "replace").decode("ascii")


def cell(value):
    text = ascii_safe(value).replace("|", "/").replace("\n", " ").strip()
    return text if text else "-"


def load_list(path):
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    rows = data.get("rows")
    if not isinstance(rows, list):
        raise SystemExit("ERROR: seat list has no rows array: %s" % path)
    return data, rows


def is_doing_nothing(row):
    commit = row.get("last_commit_minutes")
    over = isinstance(commit, (int, float)) and commit > STALE_MINUTES
    return row.get("doing") == "IDLE" or over


def round_close_output():
    proc = subprocess.run(
        [sys.executable, str(ROUND_CLOSE), "--project", PROJECT, "--round", ROUND],
        cwd=str(ROOT), capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=240)
    return proc.returncode, [ln.rstrip("\r") for ln in proc.stdout.splitlines()]


def generate(gen_list, record_path):
    data, rows = load_list(gen_list)
    rc, out_lines = round_close_output()
    close = [ln for ln in out_lines if ln.startswith("ROUND-CLOSE project=")]
    keep = [ln for ln in out_lines if ln.startswith(("REVIEWER-ON-BOX", "ORDERS scope", "PROOFS mode"))]
    graded = [ln for ln in out_lines if ln.startswith("GRADED")]
    lines = [
        "# SEAT_LIST_READ -- NFRA_CTLPLN round 19, cell CT-ai-2 (FWD-23)",
        "",
        "Generated by `.tools/tests/test_round19_seat_record.py` from the seat list's own fields "
        "(serial, kind, live, doing, project, drive, orders, commit age, summary). No seat log is opened.",
        "",
        "List: device=%s written_at=%s written_by=%s seats=%d" % (
            cell(data.get("device")), cell(data.get("written_at")), cell(data.get("written_by")), len(rows)),
        "",
        "## Seats",
        "",
        "| serial | kind | live | doing | project | drive | orders | commit age (min) | what it is doing (summary) |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for row in rows:
        lines.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
            cell(row.get("serial")), cell(row.get("kind")), cell(row.get("liveness")), cell(row.get("doing")),
            cell(row.get("project")), cell(row.get("drive")), cell(row.get("open_orders")),
            cell(row.get("last_commit_minutes")), cell(row.get("summary"))))
    flagged = [r for r in rows if is_doing_nothing(r)]
    items = ["%s (doing=%s, commit=%sm)" % (cell(r.get("serial")), cell(r.get("doing")),
                                            cell(r.get("last_commit_minutes"))) for r in flagged]
    lines += [
        "",
        "## Doing nothing",
        "",
        "DOING-NOTHING count=%d: %s" % (len(flagged), "; ".join(items) if items else "none"),
        "",
        "## Finished work and its grade (round-close-check.py --project %s --round %s, verbatim)" % (PROJECT, ROUND),
        "",
    ]
    if close:
        lines.append(close[-1])
    else:
        lines.append("ROUND-CLOSE-ABSENT rc=%d: round-close-check printed no ROUND-CLOSE line" % rc)
    lines += ["", "```text"] + keep + ["```", ""]
    if graded:
        lines += ["```text"] + graded + ["```", ""]
    else:
        lines += ["GRADED-LINES count=0: round-close-check printed no GRADED line for round %s" % ROUND, ""]
    text = "\n".join(ascii_safe(ln) for ln in lines) + "\n"
    record_path = Path(record_path)
    record_path.parent.mkdir(parents=True, exist_ok=True)
    record_path.write_text(text, encoding="utf-8", newline="\n")
    return len(rows)


def parse_record(text):
    named = set()
    idle_line = None
    close_line = None
    for raw in text.splitlines():
        line = raw.rstrip()
        if line.startswith("|") and not line.startswith("| serial") and not line.startswith("|---"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if cells and cells[0]:
                named.add(cells[0])
        elif line.startswith("DOING-NOTHING count="):
            idle_line = line
        elif line.startswith("ROUND-CLOSE project="):
            close_line = line
    return named, idle_line, close_line


def recorded_idle(idle_line):
    if idle_line is None or ":" not in idle_line:
        return set()
    body = idle_line.split(":", 1)[1].strip()
    if body == "none":
        return set()
    return {item.split(" (")[0].strip() for item in body.split("; ") if item.strip()}


def verify(list_path, record_path):
    _, rows = load_list(list_path)
    text = Path(record_path).read_text(encoding="utf-8")
    named, idle_line, close_line = parse_record(text)
    serials = [r.get("serial") for r in rows]
    seats = len(serials)
    named_count = sum(1 for s in serials if s in named)
    expected_idle = {r.get("serial") for r in rows if is_doing_nothing(r)}
    got_idle = recorded_idle(idle_line)
    reviewer = "absent"
    if close_line:
        match = re.search(r"reviewer=(\S+)", close_line)
        if match and match.group(1) == "present":
            reviewer = "present"
    ok = named_count == seats and got_idle == expected_idle and reviewer == "present"
    print("SEAT-RECORD seats=%d named=%d idle_flagged=%d round_close_reviewer=%s ok=%s" % (
        seats, named_count, len(got_idle), reviewer, ok))
    return 0 if ok else 1


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generate and verify the round-19 seat record (CT-ai-2).")
    ap.add_argument("--list", default=str(DEFAULT_LIST), help="seat list the record is verified against")
    ap.add_argument("--gen-list", default=None, help="seat list the record is generated from (default: --list)")
    ap.add_argument("--record", default=str(DEFAULT_RECORD), help="record path")
    ap.add_argument("--verify-only", action="store_true", help="do not regenerate the record")
    args = ap.parse_args(argv)
    if not args.verify_only:
        count = generate(args.gen_list or args.list, args.record)
        print("RECORD-WRITTEN %s rows=%d" % (args.record, count))
    return verify(args.list, args.record)


if __name__ == "__main__":
    sys.exit(main())
