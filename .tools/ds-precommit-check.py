def check_cross_firm_bucket_refs(tree: ast.Module, filepath_hint: str) -> list[str]:
    """Return BLOCK strings for any cross-firm S3 bucket reference in a pipeline script.

    A script under data/cot/ must never reference opal-data-bd / opal-data-inf; a script
    under data/black_diamond/ must never reference opal-data-cot. Enforces Andrew's
    2026-06-10 sovereign directive (NFRA_DTAFLP) that the bd and cot Black Diamond
    pipelines be COMPLETELY separate -- no shared code path, no cross-bucket reference.
    Scans string Constants (incl. f-string literal parts); skips docstrings + prose via
    _is_real_bucket_ref.
    """
    p = str(filepath_hint).replace('\\', '/')
    home_dir = next((d for d in _CROSS_FIRM_FOREIGN_BUCKETS if d in p), None)
    if home_dir is None:
        return []
    foreign = _CROSS_FIRM_FOREIGN_BUCKETS[home_dir]
    foreign_prefixes = _CROSS_FIRM_FOREIGN_KEY_PREFIXES.get(home_dir, ())
    skip = _docstring_constant_ids(tree)
    blocks: list[str] = []
    for node in ast.walk(tree):
        if not (isinstance(node, ast.Constant) and isinstance(node.value, str)):
            continue
        if id(node) in skip:
            continue
        for fb in foreign:
            if _is_real_bucket_ref(node.value, fb):
                blocks.append(
                    f"{filepath_hint}:{node.lineno}: BLOCKED: cross-firm bucket reference "
                    f"'{fb}' in a {home_dir.rstrip('/')} script -- the bd and cot pipelines "
                    f"must be COMPLETELY separate (Andrew sovereign 2026-06-10, NFRA_DTAFLP). "
                    f"A {home_dir.rstrip('/')} script may reference ONLY its own firm bucket. "
                    f"Remove the cross-firm reference."
                )
        for fp in foreign_prefixes:
            # Trailing-slash prefix in the constant = a real key reference, not prose
            # (mirrors the f'{bucket}/' arm of _is_real_bucket_ref).
            if fp in node.value:
                blocks.append(
                    f"{filepath_hint}:{node.lineno}: BLOCKED: cross-firm KEY-PREFIX reference "
                    f"'{fp}' in a {home_dir.rstrip('/')} script -- the shared vendor prefix "
                    f"spans both firms, and firm separation binds BELOW the bucket "
                    f"(Andrew GO 2026-08-11 on the CTO gate candidate; NFRA_DTAFLP). "
                    f"A {home_dir.rstrip('/')} script may reference ONLY its own firm's keys. "
                    f"Remove the cross-firm reference."
                )
    # NFRA_DTAFLP seed-import bypass (COO GO 2026-06-10): an AUTHORIZED one-time
    # preservation commit of a forked-from-bd cot seed legitimately carries cross-firm
    # refs (the bd-derived code being committed to git for the first time, before the
    # divergence-phase retarget). DTAFLP_SEED_IMPORT=1 suppresses ONLY this cross-firm
    # check; every other gate check (py_compile, undefined-name, future-annot, silver-id,
    # sync-guard) stays live. Each suppression writes a forensic audit line. The runtime
    # IAM cross-bucket Deny still blocks any actual cross-firm write regardless.
    if blocks and os.environ.get('DTAFLP_SEED_IMPORT') == '1':
        _audit_seed_import_bypass(filepath_hint, foreign, len(blocks))
        print(
            f"WARN: DTAFLP_SEED_IMPORT=1 -- bypassed {len(blocks)} cross-firm bucket ref(s) "
            f"in {filepath_hint} (audited to org/dtaflp-seed-import-audit.log). AUTHORIZED "
            f"preservation-seed commit; retarget in the divergence phase. IAM Deny still "
            f"blocks runtime cross-firm writes.",
            file=sys.stderr,
        )
        return []
    return blocks


def _path_is_astdedup_scope(filepath: str) -> bool:
    p = str(filepath).replace('\\', '/')
    return any(fnmatch.fnmatch(p, pat) for pat in _ASTDEDUP_PATTERNS)


def _astdedup_call_name(node: ast.expr) -> str | None:
    """Bare callable name for as_completed(...)/pool.imap_unordered(...) detection."""
    if isinstance(node, ast.Call):
        if isinstance(node.func, ast.Name):
            return node.func.id
        if isinstance(node.func, ast.Attribute):
            return node.func.attr
    return None


def _astdedup_scope_nodes(fn):
    """Yield every node inside fn's own scope, not crossing into a nested def/lambda."""
    stack = list(fn.body)
    while stack:
        n = stack.pop()
        yield n
        for child in ast.iter_child_nodes(n):
            if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef, ast.Lambda)):
                continue
            stack.append(child)


def _astdedup_root_name(node: ast.expr) -> str | None:
    """Walk a receiver chain (Subscript/Attribute/Call) down to its base Name id."""
    cur = node
    while True:
        if isinstance(cur, ast.Name):
            return cur.id
        if isinstance(cur, ast.Subscript):
            cur = cur.value
        elif isinstance(cur, ast.Attribute):
            cur = cur.value
        elif isinstance(cur, ast.Call):
            cur = cur.func
        else:
            return None


def _astdedup_containers(fn) -> tuple[set, int]:
    """Names .append()/.extend()'d (a Name receiver) inside a completion-order loop body.

    Index-slot assembly (`results[i] = ...`, a Subscript target) is deterministic and is
    deliberately NOT collected -- that is the CLASS-I shape that must stay silent.
    """
    containers = set()
    first_ln = 0
    for n in _astdedup_scope_nodes(fn):
        if isinstance(n, (ast.For, ast.AsyncFor)) and \
                _astdedup_call_name(n.iter) in ('as_completed', 'imap_unordered'):
            for inner in ast.walk(n):
                if (isinstance(inner, ast.Call)
                        and isinstance(inner.func, ast.Attribute)
                        and inner.func.attr in ('append', 'extend')
                        and isinstance(inner.func.value, ast.Name)):
                    containers.add(inner.func.value.id)
                    first_ln = first_ln or n.lineno
    return containers, first_ln


def _astdedup_concat_frames(fn, containers: set) -> set:
    """Names assigned from a pd.concat(...)/pd.DataFrame(...) whose args reference a
    completion-order container -- the frame that carries the random ordering."""
    frames = set()
    for n in _astdedup_scope_nodes(fn):
        if not isinstance(n, ast.Assign):
            continue
        val = n.value
        if not (isinstance(val, ast.Call)
                and _astdedup_call_name(val) in ('concat', 'DataFrame')):
            continue
        refs = {c.id for c in ast.walk(val) if isinstance(c, ast.Name)}
        if not (refs & containers):
            continue
        for tgt in n.targets:
            if isinstance(tgt, ast.Name):
                frames.add(tgt.id)
    return frames


def _astdedup_keep_is_order_sensitive(call: ast.Call) -> bool:
    """drop_duplicates is order-sensitive when keep is 'last'/'first' or omitted (default 'first')."""
    for kw in call.keywords:
        if kw.arg == 'keep':
            return isinstance(kw.value, ast.Constant) and kw.value.value in ('last', 'first')
    return True  # keep omitted -> default 'first' -> order-sensitive


def _astdedup_is_sort_guarded(call: ast.Call) -> bool:
    """True if the drop_duplicates receiver is itself a `.sort_values(...)` call (a total-order
    sort immediately before the dedup makes the survivor deterministic)."""
    recv = call.func.value if isinstance(call.func, ast.Attribute) else None
    return (isinstance(recv, ast.Call)
            and isinstance(recv.func, ast.Attribute)
            and recv.func.attr == 'sort_values')


def check_completion_order_dedup(tree: ast.Module, filepath_hint: str) -> list:
    """Return WARN/ERROR strings for the CLASS-N completion-order-build -> order-sensitive-dedup
    conjunction (ADHC_GLDINC.AST-DEDUP). Fires per function scope ONLY when all three hold:
    (1) a list is .append()/.extend()'d inside a `for x in as_completed(...)`/imap_unordered loop;
    (2) that container is pd.concat(...)'d into a frame; (3) that frame is .drop_duplicates()'d
    order-sensitively (keep last/first or default) WITHOUT a chained .sort_values(). Severity is
    governed by _ASTDEDUP_SEVERITY. Only scans paths in _ASTDEDUP_PATTERNS."""
    if not _path_is_astdedup_scope(filepath_hint):
        return []
    label = 'BLOCKED' if _ASTDEDUP_SEVERITY == 'error' else 'WARN'
    findings = []
    for node in ast.walk(tree):
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        containers, build_ln = _astdedup_containers(node)
        if not containers:
            continue
        frames = _astdedup_concat_frames(node, containers)
        if not frames:
            continue
        for n in _astdedup_scope_nodes(node):
            if (isinstance(n, ast.Call)
                    and isinstance(n.func, ast.Attribute)
                    and n.func.attr == 'drop_duplicates'
                    and _astdedup_keep_is_order_sensitive(n)
                    and not _astdedup_is_sort_guarded(n)
                    and _astdedup_root_name(n.func.value) in frames):
                findings.append(
                    f"{filepath_hint}:{n.lineno}: {label}: function '{node.name}' "
                    f"completion-order build (append under as_completed @L{build_ln}) feeds an "
                    f"order-sensitive drop_duplicates @L{n.lineno} not preceded by a total-order "
                    f"sort_values -- CLASS-N nondeterministic survivor (survivor depends on thread "
                    f"completion order; served values flip run-to-run on identical data). Fix: "
                    f"index-slot assembly (results[i]=...) OR a total-order .sort_values(...) "
                    f"before .drop_duplicates() (ADHC_GLDINC.AST-DEDUP)."
                )
    return findings


def _norm(p: str) -> str:
    return os.path.normpath(p).replace(os.sep, '/')


def check_dual_pipeline_sync(filepath_hint: str) -> str | None:
    """If the scanned file is a member of a byte-identical synced GROUP (N>=2 copies that MUST
    be identical -- the bd/orion/smartx runtimes are separate, so a shared helper is N physical
    copies + this mechanical gate = one enforced canonical impl), assert ALL copies exist and are
    byte-for-byte identical. Returns an error string on divergence/missing, else None. Fires on
    any commit touching any copy (MDLP_DISTFIX I3 / CTO dual-pipeline-sync ruling 2026-06-05)."""
    norm = _norm(os.path.abspath(filepath_hint))
    for group in _SYNCED_HELPER_GROUPS:
        members = [_norm(m) for m in group]
        root = None
        for m in members:
            if norm == m or norm.endswith('/' + m):
                root = norm[:len(norm) - len(m)]
                break
        if root is None:
            continue
        paths = [Path(root + m) for m in members]
        try:
            blobs = [p.read_bytes() for p in paths]
        except FileNotFoundError as e:
            return (f"{filepath_hint}: SYNC-GUARD ERROR: synced helper group missing a copy "
                    f"({e}); ALL of {group} must exist + be byte-identical (MDLP_DISTFIX I3).")
        canon = blobs[0]
        if any(b != canon for b in blobs[1:]):
            return (f"{filepath_hint}: SYNC-GUARD ERROR: synced helper group DIVERGED -- the copies "
                    f"{group} are NOT byte-identical. They are ONE canonical impl; re-sync "
                    f"(`cp` the canonical onto the others) before committing "
                    f"(MDLP_DISTFIX I3 / CTO dual-pipeline-sync ruling 2026-06-05).")
    return None


def scan_file(filepath, verbose=False, strict=False):
    path = Path(filepath)
    source = path.read_text(encoding="utf-8")
    tree = ast.parse(source, filename=str(path))

    rc = 0

    # PEP-604 / future-annotations gate (ADHC_DSFLOW.004)
    err = check_future_annotations_source(source, str(filepath))
    if err:
        print(err, file=sys.stderr)
        rc = 1

    # Dual-pipeline byte-identical sync-guard (MDLP_DISTFIX I3 / CTO ruling 2026-06-05)
    sync_err = check_dual_pipeline_sync(str(filepath))
    if sync_err:
        print(sync_err, file=sys.stderr)
        rc = 1

    # Silver canonical ID dtype gate (ADVI_INFNNA.ID-DTYPE-ENFORCEMENT)
    blocks, warns = check_silver_id_dtype(source, tree, str(filepath))
    for msg in blocks:
        print(msg, file=sys.stderr)
    for msg in warns:
        print(msg, file=sys.stderr)
    if blocks:
        rc = 1

    # Cross-firm bucket contamination gate (Andrew sovereign 2026-06-10, NFRA_DTAFLP)
    xfirm_blocks = check_cross_firm_bucket_refs(tree, str(filepath))
    for msg in xfirm_blocks:
        print(msg, file=sys.stderr)
    if xfirm_blocks:
        rc = 1

    # Completion-order build -> order-sensitive dedup CLASS-N gate (ADHC_GLDINC.AST-DEDUP)
    astdedup_msgs = check_completion_order_dedup(tree, str(filepath))
    for msg in astdedup_msgs:
        print(msg, file=sys.stderr)
    if astdedup_msgs and _ASTDEDUP_SEVERITY == 'error':
        rc = 1

    has_star = any(
        isinstance(n, ast.ImportFrom) and any(a.name == "*" for a in n.names)
        for n in ast.walk(tree)
    )
    if has_star and not strict:
        if verbose:
            print(f"{filepath}: skipped (star import; use --strict to scan)", file=sys.stderr)
        return rc

    module_defined = _collect_module_defined(tree)
    if verbose:
        print(f"{filepath}: {len(module_defined)} module names", file=sys.stderr)

    scanner = Scanner(str(filepath), module_defined)
    scanner.visit(tree)
    for fp, lineno, name in scanner.misses:
        print(f"{fp}:{lineno}: undefined name '{name}'", file=sys.stderr)
    return max(rc, 1 if scanner.misses else 0)


def main():
    ap = argparse.ArgumentParser(description="DS pre-commit AST undefined-name scanner (stdlib-only).")
    ap.add_argument("files", nargs="+", help="Python files to scan")
    ap.add_argument("--verbose", action="store_true", help="Print defined-set size per file")
    ap.add_argument("--strict", action="store_true", help="Scan even files with star imports")
    args = ap.parse_args()
    rc = 0
    for f in args.files:
        rc = max(rc, scan_file(f, verbose=args.verbose, strict=args.strict))
    sys.exit(rc)


if __name__ == "__main__":
    main()
