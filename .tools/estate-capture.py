"""ESTATE REPORT -- the text-input capture layer (Andrew ruling 7 + 7a; sovereign mandate).

Andrew ruling 7, VERBATIM: "every single text of user input from me into a terminal session needs to
be tracked somewhere on a day by day basis."
Andrew ruling 7a, VERBATIM: "also we need to figure out how to track all my text inputs and have that
saved somewhere."

*** THIS RUNS DEVICE-SIDE, NOT ON THE EC2 RUNNER, AND THAT IS FORCED -- NOT A PREFERENCE. ***
The transcripts live at ~/.claude/projects/ on each physical device. They are NOT in the repo and NOT
in S3. The estate-report EC2 runner clones the repo, so it STRUCTURALLY CANNOT SEE THEM. Any design
that puts capture on the runner captures nothing and produces a perfectly well-formed empty store --
the exact "looks complete, is empty" failure this whole pipeline exists to refuse.
So: this tool runs on the DEVICE, uploads to S3; the runner READS the uploaded store.
It is also why site-Z is a DECLARED GAP rather than an oversight: a second device needs this tool
running on it, and until it does, "every single text" is device-scoped and every day's manifest must
say so.

WHAT IT EXTRACTS, and the measured reason the obvious version is wrong:
Harness transcripts store turn-boundary input as `type: user`, but MID-TURN input as
`queue-operation` + `attachment` -- NEVER as `user`. Measured against ground truth on session
339beee1: Andrew sent 5 messages; 3 were mid-turn. A naive `type == "user"` extractor captures 40%
AND admits skill bodies, system reminders, task notifications and tool_results as if he had typed
them -- false negatives and false positives at once. The 3 it drops were the highest-signal messages
in that session (two architecture rulings and a standing hold).

FAIL-CLOSED PROVENANCE, one layer below ruling 6's: HUMAN / HARNESS / UNCLASSIFIED. Anything not
positively identifiable as human-typed is NEVER stored as Andrew's words. A missed nugget is absent;
a forged one is believed.
"""

from __future__ import annotations

import argparse
import glob
import hashlib
import json
import os
import re
import socket
import sys
from datetime import datetime, timezone

# Markers that prove a payload is harness-generated rather than typed by a human. Substring match:
# these strings do not occur in ordinary prose, and over-matching costs a dropped message (visible,
# recoverable) while under-matching costs a FORGED QUOTE (invisible, believed).
HARNESS_MARKERS = (
    "<system-reminder>",
    "SYSTEM NOTIFICATION",
    "<task-notification>",
    "<command-name>",
    "<command-message>",
    "<local-command-stdout>",
    # ADDED 2026-07-31 after a CORPUS-SCALE measurement: this was the single most
    # repeated "utterance" in the whole store -- 130 records of pure harness preamble
    # ("Caveat: The messages below were generated by the user while running local
    # commands...") filed as Andrew's words. `<local-command-stdout>` was listed and its
    # SIBLING TAG was not, so the guard read complete while a whole class walked past it.
    # This is the FORGED-QUOTE failure the module docstring calls the worse one, and it
    # was invisible at fixture scale: a precision check over 14 records from 2 sessions
    # reported ZERO false positives while 130 sat in the corpus. A CLEAN PRECISION RESULT
    # ON A SMALL DENOMINATOR SAYS NOTHING ABOUT THE CORPUS.
    "<local-command-caveat>",
    "Base directory for this skill:",
    "Launching skill:",
    "[Request interrupted",
    "<user-prompt-submit-hook>",
)

# Checked with startswith(), NOT substring -- deliberately, and the distinction is
# load-bearing. The compaction preamble is harness-authored when it OPENS a payload, but
# Andrew may legitimately QUOTE it back mid-sentence while discussing a compaction. A
# substring rule would silently eat that real message; an opening-anchor rule cannot.
# (83 such preambles were stored as Andrew's words before this existed.)
HARNESS_PREFIXES = (
    "This session is being continued from a previous conversation",
)

# A skill body is delivered wearing the user role. It is long, structured, and NOT Andrew.
# This regex requires "**Refreshed" / "**Base directory" on the second line and therefore
# MISSES any skill whose body does not open that way -- measured: 2 escaped it, one of
# them 155,719 characters of `# Update Config Skill`, filed as something Andrew typed.
SKILL_BODY_RE = re.compile(r"^#\s+\S+.*\n.*\*\*(Refreshed|Base directory)", re.S)

# The backstop for the class the regex above misses. A markdown H1 opening a payload
# delivered in the user role is a DOCUMENT, not a typed message.
# MEASURED BEFORE ADOPTING, because a shape rule that eats real messages is worse than the
# defect it fixes: across 297 sessions / 3,628 stored utterances, exactly TWO begin with
# "# " and BOTH are skill bodies. Zero of Andrew's genuine messages open with a heading.
# It routes to UNCLASSIFIED, not HARNESS, on purpose -- see classify_text.
DOCUMENT_SHAPE_RE = re.compile(r"^#\s+\S")


def utcnow() -> str:
    return datetime.now(timezone.utc).isoformat()


def device_id() -> str:
    """Stable device label. Goes in the S3 key so a partial day is visibly partial."""
    return os.environ.get("ESTATE_DEVICE_ID") or socket.gethostname() or "unknown-device"


# HARNESS DISPLAY PREFIXES: glyphs the harness prepends to mid-turn input for rendering. Andrew did
# not type these. Kept as an explicit, enumerated list rather than a general "strip leading
# punctuation" rule -- a general rule would eventually eat a real character from a real sentence, and
# nobody would notice because the result would still read fine.
DISPLAY_PREFIXES = ("❯ ", "❯", "> ", "› ")


def _strip_display_prefix(text: str) -> str:
    t = text
    for p in DISPLAY_PREFIXES:
        if t.startswith(p):
            return t[len(p):].lstrip()
    return t


def _text_of(msg: object) -> str:
    if isinstance(msg, str):
        return msg
    if isinstance(msg, dict):
        c = msg.get("content")
        if isinstance(c, str):
            return c
        if isinstance(c, list):
            return "\n".join(
                p.get("text", "") for p in c if isinstance(p, dict) and p.get("type") == "text"
            )
    return ""


def _has_tool_result(msg: object) -> bool:
    if isinstance(msg, dict):
        c = msg.get("content")
        if isinstance(c, list):
            return any(isinstance(p, dict) and p.get("type") == "tool_result" for p in c)
    return False


def classify_text(text: str, row: dict) -> tuple[str, str]:
    """HUMAN / HARNESS / UNCLASSIFIED -- fail-closed. Returns (label, why).

    Only HUMAN is ever stored as Andrew's words. UNCLASSIFIED is retained in the store but flagged,
    so a later reader can audit what the filter was unsure about -- silently dropping the ambiguous
    class would hide the filter's own error rate, and an error rate nobody can see is one nobody
    fixes.

    *** THE MIDDLE BUCKET WAS DEAD, AND A DEAD MIDDLE BUCKET IS NOT FAIL-CLOSED. ***
    Measured 2026-07-31 across 297 sessions / 197,757 rows: UNCLASSIFIED fired **zero** times.
    The only route to it was `startswith("<") and endswith(">") and len < 200`, which almost
    nothing satisfies -- so a three-way classifier ran as a BINARY one, and every ambiguous
    payload was forced to HUMAN (stored as Andrew's words) or HARNESS (dropped). There was no
    channel for "I don't know," so NOT-KNOWING RENDERED AS CONFIDENCE -- and it rendered in the
    direction that forges quotes. The document-shape rule below is routed here, not to HARNESS,
    deliberately: retained-and-flagged is recoverable in both directions, whereas a drop at
    capture is unrecoverable (CVO ruling 2026-07-31) and a HUMAN label is a forgery.
    """
    if _has_tool_result(row.get("message")):
        return ("HARNESS", "tool_result payload")
    t = (text or "").strip()
    if not t:
        return ("HARNESS", "empty/non-text")
    for marker in HARNESS_MARKERS:
        if marker in t:
            return ("HARNESS", "harness marker %r" % marker)
    for prefix in HARNESS_PREFIXES:
        if t.startswith(prefix):
            return ("HARNESS", "harness prefix %r" % prefix)
    if SKILL_BODY_RE.match(t):
        return ("HARNESS", "skill body shape")
    if t.startswith("<") and t.endswith(">") and len(t) < 200:
        return ("UNCLASSIFIED", "bare tag-like payload")
    if DOCUMENT_SHAPE_RE.match(t):
        return ("UNCLASSIFIED", "markdown-document shape (H1 opener), not typed prose")
    return ("HUMAN", "no harness marker; free text")


def extract_session(path: str) -> tuple[list, dict]:
    """Union of user + queue-operation + attachment, de-duplicated, classified.

    THE UNION IS THE WHOLE POINT and it is also why de-dup is REQUIRED rather than hygiene: one
    mid-turn message appears in BOTH queue-operation and attachment, so the union that fixes the 40%
    miss GUARANTEES duplicates. Keying on a row uuid would fail -- the same utterance carries
    different ids across row types -- so the key is content-based.
    """
    rows = []
    with open(path, "r", encoding="utf-8", errors="replace") as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            try:
                rows.append(json.loads(line))
            except Exception:  # noqa: BLE001
                continue

    session_id = ""
    for r in rows:
        if r.get("sessionId"):
            session_id = str(r["sessionId"])
            break
    if not session_id:
        session_id = os.path.splitext(os.path.basename(path))[0]

    seen: dict[str, dict] = {}
    counts = {"rows_scanned": 0, "candidates": 0}
    labels = {"HUMAN": 0, "HARNESS": 0, "UNCLASSIFIED": 0}

    for r in rows:
        if r.get("type") not in ("user", "queue-operation", "attachment"):
            continue
        counts["rows_scanned"] += 1
        # A queue-operation/attachment row nests the payload in varying places; search the row for
        # any message-shaped text rather than assuming one field. Assuming a field shape is exactly
        # the defect that produced the UNRESOLVED bucket earlier in this build.
        texts = []
        m = r.get("message")
        if m is not None:
            texts.append((_text_of(m), r))
        for key in ("prompt", "text", "content", "value"):
            v = r.get(key)
            if isinstance(v, str) and v.strip():
                texts.append((v, r))
            elif isinstance(v, dict):
                tv = _text_of(v)
                if tv.strip():
                    texts.append((tv, r))
        for text, row in texts:
            if not text or not text.strip():
                continue
            counts["candidates"] += 1
            label, why = classify_text(text, row)
            labels[label] += 1
            if label == "HARNESS":
                continue
            # Whitespace-collapse ONLY for the key. NEVER case-fold, NEVER strip punctuation --
            # the stored text is EVIDENCE and must stay byte-faithful to what he typed.
            norm = " ".join(text.split())
            key = hashlib.sha256((session_id + "\x1e" + norm).encode("utf-8")).hexdigest()
            if key in seen:
                seen[key]["row_types"] = sorted(set(seen[key]["row_types"] + [r.get("type")]))
                continue
            seen[key] = {
                "dedup_key": key,
                "session_id": session_id,
                "provenance": label,
                "provenance_why": why,
                "row_types": [r.get("type")],
                "ts": r.get("timestamp") or r.get("ts"),
                # TWO FIELDS ON PURPOSE, and the distinction is load-bearing for quoting.
                # `text` is BYTE-FAITHFUL to the transcript -- it is the evidence, and it is what any
                # dispute resolves against. But the harness prefixes mid-turn input with a display
                # marker ("> ") that ANDREW DID NOT TYPE. Quoting `text` verbatim would attribute a
                # harness glyph to him -- a small forgery, but a forgery, and exactly the class ruling
                # 6's fail-closed provenance exists to refuse.
                # `text_for_quote` is the same string with ONLY known harness display prefixes
                # removed. Nothing else is normalized: no case-folding, no punctuation stripping,
                # no whitespace rewriting beyond the prefix.
                "text": text,
                "text_for_quote": _strip_display_prefix(text),
            }

    out = sorted(seen.values(), key=lambda d: (str(d.get("ts") or ""), d["dedup_key"]))
    meta = {
        "session_id": session_id,
        "source_path": path,
        "rows_scanned": counts["rows_scanned"],
        "candidate_payloads": counts["candidates"],
        "by_label": labels,
        "stored": len(out),
        "captured_at": utcnow(),
        "device": device_id(),
    }
    return out, meta


def _utc_date_of(rec: dict) -> str:
    """UTC day token of a record's transcript timestamp, or '' when unbucketable.

    Harness timestamps are ISO-8601 UTC ('...Z'), so the first 10 chars ARE the UTC
    date -- the same token grammar as the report-day manifest key (manifest/{D}.json),
    which is what keeps capture and manifest joinable on one date (CVO 3b)."""
    ts = str(rec.get("ts") or "")
    return ts[:10] if re.match(r"^\d{4}-\d{2}-\d{2}$", ts[:10]) else ""


def upload_days(all_recs: list, bucket: str, dates: list) -> int:
    """B6-1 upload leg (TO F3_CAPTURE_UPLOADER.B6). Writes each requested UTC day's
    HUMAN + UNCLASSIFIED records (HARNESS never reaches the store -- extract_session
    drops it) to s3://{bucket}/text-input/{YYYY-MM-DD}/{device_id}.json.

    - PER-DEVICE key: a partial day is VISIBLY partial (CTO 3a: denominator in key form).
    - IDEMPOTENT: re-run overwrites that day's device file.
    - BRONZE: records upload byte-faithful, untouched -- classification is a
      friction-time act, never an upload-time one (Rule 17a).
    - NO-DATA-DAY LAW (CVO 3b rider a): an empty day is NO-PARTITION, LOUD -- never a
      silent empty object. All-days-empty exits 2 so the schedule's history shows it.
    - Every put is READ BACK and sha-compared before it is called landed -- rc=0 is
      not evidence and neither is the put's HTTP 200 (the served artifact is).
    Returns 0 (>=1 day landed+verified, empties loudly named), 1 (put/verify failure),
    2 (every requested day empty)."""
    import boto3  # lazy: print/--json modes must not require it

    s3 = boto3.client("s3")
    dev = device_id()
    by_date: dict[str, list] = {}
    unbucketable = 0
    for rec in all_recs:
        d = _utc_date_of(rec)
        if d:
            by_date.setdefault(d, []).append(rec)
        else:
            unbucketable += 1
    if unbucketable:
        # Excluded from every day file, but DECLARED in each uploaded object's counts --
        # an exclusion without a printed denominator reads as coverage.
        print("WARN: %d record(s) carry no bucketable UTC timestamp -- excluded from day files, "
              "count declared in each uploaded object" % unbucketable, file=sys.stderr)

    uploaded, empty = [], []
    for d in dates:
        recs = by_date.get(d, [])
        if not recs:
            print("NO-PARTITION %s: zero HUMAN/UNCLASSIFIED records for this device on that UTC day "
                  "-- refusing to write an empty object (no-data-day law)" % d, file=sys.stderr)
            empty.append(d)
            continue
        body_obj = {
            "schema": "estate-text-input/v1",
            "date": d,
            "device": dev,
            "uploaded_at": utcnow(),
            "counts": {
                "records": len(recs),
                "by_label": {
                    "HUMAN": sum(1 for r in recs if r["provenance"] == "HUMAN"),
                    "UNCLASSIFIED": sum(1 for r in recs if r["provenance"] == "UNCLASSIFIED"),
                },
                "sessions": len({r["session_id"] for r in recs}),
                "ts_unbucketable_excluded_corpuswide": unbucketable,
            },
            "records": recs,
        }
        body = json.dumps(body_obj, ensure_ascii=False, sort_keys=True).encode("utf-8")
        sha = hashlib.sha256(body).hexdigest()
        key = "text-input/%s/%s.json" % (d, dev)
        s3.put_object(Bucket=bucket, Key=key, Body=body,
                      ContentType="application/json",
                      Metadata={"content-sha256": sha, "producer": "estate-capture.py b6-1"})
        served = s3.get_object(Bucket=bucket, Key=key)["Body"].read()
        served_sha = hashlib.sha256(served).hexdigest()
        if served_sha != sha:
            print("ERROR: read-back sha mismatch for s3://%s/%s (sent %s served %s) -- upload NOT "
                  "landed" % (bucket, key, sha[:12], served_sha[:12]), file=sys.stderr)
            return 1
        print("OK: s3://%s/%s -- %d records (%d sessions), read-back sha verified %s"
              % (bucket, key, len(recs), body_obj["counts"]["sessions"], sha[:12]))
        uploaded.append(d)

    if not uploaded:
        print("NO-PARTITION on ALL %d requested day(s) (%s) -- nothing written; a capture cadence "
              "that captured nothing must not read green" % (len(dates), ", ".join(dates)),
              file=sys.stderr)
        return 2
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="ESTATE REPORT device-side text-input capture")
    ap.add_argument("--project-dir", default=os.path.expanduser(
        "~/.claude/projects/C--Users-AndrewBerman-Desktop-ajb-workspace"))
    ap.add_argument("--session", help="single session id/file to extract (fixture mode)")
    ap.add_argument("--json", action="store_true", help="emit the extracted records as JSON")
    ap.add_argument("--upload", action="store_true",
                    help="B6-1: upload day-partitioned records to S3 (text-input/{date}/{device}.json)")
    ap.add_argument("--date", help="target UTC day YYYY-MM-DD for --upload (default: today UTC)")
    ap.add_argument("--catchup-days", type=int, default=0,
                    help="with --upload: also (re-)upload N prior days -- the daily schedule runs 7 "
                         "so an off/lidded laptop self-heals a week of day files idempotently")
    ap.add_argument("--bucket", default="opal-estate-report")
    args = ap.parse_args(argv)
    if args.date and not re.match(r"^\d{4}-\d{2}-\d{2}$", args.date):
        ap.error("--date must be YYYY-MM-DD")

    if args.session:
        files = [p for p in glob.glob(os.path.join(args.project_dir, "*.jsonl"))
                 if args.session in os.path.basename(p)]
    else:
        files = glob.glob(os.path.join(args.project_dir, "*.jsonl"))
    if not files:
        print("NO TRANSCRIPTS FOUND under %s -- refusing to report an empty capture as a complete one"
              % args.project_dir, file=sys.stderr)
        return 2

    all_recs, metas = [], []
    for p in files:
        recs, meta = extract_session(p)
        all_recs.extend(recs)
        metas.append(meta)

    if args.upload:
        from datetime import timedelta
        anchor = args.date or datetime.now(timezone.utc).strftime("%Y-%m-%d")
        base = datetime.strptime(anchor, "%Y-%m-%d")
        dates = [(base - timedelta(days=n)).strftime("%Y-%m-%d")
                 for n in range(args.catchup_days + 1)]
        return upload_days(all_recs, args.bucket, dates)

    if args.json:
        print(json.dumps({"records": all_recs, "meta": metas}, indent=2))
    else:
        tot = {"HUMAN": 0, "HARNESS": 0, "UNCLASSIFIED": 0}
        for m in metas:
            for k in tot:
                tot[k] += m["by_label"][k]
        print("sessions: %d | rows scanned: %d | stored: %d"
              % (len(metas), sum(m["rows_scanned"] for m in metas), len(all_recs)))
        print("labels: %s" % tot)
    return 0


if __name__ == "__main__":
    sys.exit(main())
